def markers() -> list[Marker]:
    """The table as a fresh list (`Marker` is frozen, so sharing instances is safe)."""
    return list(MARKERS)


def by_id(marker_id: str) -> Marker | None:
    for marker in MARKERS:
        if marker.id == marker_id:
            return marker
    return None


def digest() -> str:
    """Digest of the table — part of the classifier's cache key (see `cache.py`)."""
    h = hashlib.sha256()
    for marker in MARKERS:
        h.update(marker.digest_token().encode("utf-8", "replace"))
        h.update(b"\x1f")
    return h.hexdigest()[:16]


@dataclass(frozen=True)
class Hit:
    """One marker that matched, and where."""

    marker: Marker
    matched: str
    line: int

    @property
    def id(self) -> str:
        return self.marker.id

    @property
    def cls(self) -> str:
        return self.marker.cls

    @property
    def weight(self) -> float:
        return self.marker.weight

    def quote(self) -> str:
        """The matched text, clipped — it goes into the sentence a reviewer reads."""
        text = " ".join(self.matched.split())
        return text if len(text) <= 60 else text[:59] + "…"

    def as_dict(self) -> dict:
        return {"marker": self.id, "class": self.cls, "weight": self.weight,
                "matched": self.quote(), "line": self.line, "note": self.marker.note}


def head_of(text: str) -> str:
    """The window markers are allowed to read: the first `HEAD_LINES` lines / `HEAD_BYTES`."""
    return "\n".join(text.split("\n", HEAD_LINES)[:HEAD_LINES])[:HEAD_BYTES]


def scan(text: str, *, table: tuple[Marker, ...] = MARKERS) -> list[Hit]:
    """Every marker matching the head of `text`, in table order.

    Callers get *all* hits, not just the winner: the receipts are the point, and a file with
    three generator banners in it is a file worth three receipts about.
    """
    head = head_of(text or "")
    if not head.strip():
        return []
    starts = _line_starts(head)
    hits: list[Hit] = []
    for marker in table:
        matched, line = "", 0
        for literal in marker.literals:
            index = head.find(literal)
            if index >= 0:
                matched, line = literal, _line_of(starts, index)
                break
        if not matched and marker.regex:
            found = marker.compiled().search(head)
            if found:
                matched, line = found.group(0), _line_of(starts, found.start())
        if matched:
            hits.append(Hit(marker=marker, matched=matched, line=line))
    return hits


def _line_starts(text: str) -> list[int]:
    out = [0]
    for index, char in enumerate(text):
        if char == "\n":
            out.append(index + 1)
    return out


def _line_of(starts: list[int], index: int) -> int:
    """1-based line number of `index` within the head, by binary search."""
    lo, hi = 0, len(starts) - 1
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if starts[mid] <= index:
            lo = mid
        else:
            hi = mid - 1
    return lo + 1
