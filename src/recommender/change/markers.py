"""The content-marker table: what the *bytes* of a file say about what it is.

`e0.9` decides from the path and nothing else;
[docs/concepts/paths.md](../../../docs/concepts/paths.md) §9 explains why the rule table
must not sniff. This is the other half of that sentence: the sniff lives *here*, above the
table, where it can be overruled by it — `recommender.change.policy` ranks a configured
path assertion over every marker in this file. What is in a table rather than inline in
`evidence.py` is the part a reviewer has to be able to grep for, version, and digest:

* **Every marker has a stable `id`** (`gen.protoc`, `lock.cargo`, `mig.goose`, `test.rust`)
  printed in the reason string, exactly like a taxonomy rule id. "It looked generated" is
  not a receipt; *marker `gen.protoc` matched `Code generated by protoc-gen-go` on line 3*
  is.
* **`MARKERS_VERSION` and `digest()`** belong to the classifier's cache key. A marker table
  change invalidates cached classifications (ADR-004 §6's table-change event, in its
  content form), so the version is bumped in the same commit as any pattern change.
* **Literals plus a handful of small regexes, all anchored to the head of the file.**
  Generators put their banner at the top; scanning 10 MB of minified JavaScript for the
  words "do not edit" would be slow *and* wrong, because the phrase occurs in prose and in
  hand-written comments. `HEAD_BYTES`/`HEAD_LINES` are the whole budget.
* **Anchoring is load-bearing, so the regexes say so.** A marker that would fire on the
  middle of a line ("…generated by the pipeline…") is a marker that classifies prose, so
  banner regexes are line-anchored and require a comment token or the words
  "this file was". Specific tools (protoc, Thrift, FlatBuffers, openapi-generator) get
  their own literal entries with a higher weight than the generic banner.

Weights are declared here and interpreted by `policy.py`; they are clustered into two bands
so the precedence story is short:

* **decisive (≥ `policy.DECISIVE`)** — a fact about the bytes that a *built-in* path guess
  may not overrule: a generated-code banner, a package manager's lock header,
  `-- +goose Up`, an ELF magic number.
* **suggestive (< `policy.DECISIVE`)** — evidence worth printing and worth a confidence
  bump, not worth an override on its own: test markers, minification, a shebang, a file
  named by a build config.

`tests/test_change_classifier_contract.py` pins the digest, asserts every id is unique and
every claimed class exists in `recommender.taxonomy.classes`, and refuses a decisive marker
whose `note` is empty — a marker a reviewer cannot read is a marker they will not trust.
"""

from __future__ import annotations

import hashlib
import re
from dataclasses import dataclass

from recommender.taxonomy import classes as C

#: Version of this table. Bump with any pattern change; the classifier's cache key changes
#: with it, which is the point.
MARKERS_VERSION = 1

#: How much of the head of a file a marker may look at. Big enough for any generator banner
#: plus its imports, small enough that a 40 MB committed asset costs the same as a 2 KB one.
HEAD_BYTES = 4096
HEAD_LINES = 40

#: Weight at or above which a marker is *decisive*. `policy.DECISIVE` is the same number and
#: is what the combination actually uses; this copy exists so `fathom change markers` can
#: print the band without importing the policy.
DECISIVE = 0.75


@dataclass(frozen=True)
class Marker:
    """One named claim about file content.

    `literals` are matched case-sensitively: a generated-code banner is a string a tool
    wrote, and case-insensitive matching would catch the sentence in a human's prose.
    `regex` is for banners with a variable part, and is compiled once at import. `where` is
    `head` for every marker today — "generators write their banner at the top" is what makes
    the scan cheap, and a marker that needed the whole file would be a different feature.
    """

    id: str
    cls: str
    weight: float
    note: str
    literals: tuple[str, ...] = ()
    regex: str = ""
    where: str = "head"

    def compiled(self) -> re.Pattern | None:
        return re.compile(self.regex, re.MULTILINE) if self.regex else None

    def decisive(self) -> bool:
        return self.weight >= DECISIVE

    def digest_token(self) -> str:
        return "|".join((self.id, self.cls, "%.2f" % self.weight, self.regex,
                         ",".join(self.literals)))


def _m(marker_id, cls, weight, note, *, literals=(), regex=""):
    return Marker(id=marker_id, cls=cls, weight=weight, note=note,
                  literals=tuple(literals), regex=regex)


