"""The spike runner: build the corpus, run the arms, audit them, score them, write the report.

```
python3 -m recommender.narrative collect --deltas /tmp/deltas \
        --spike crates/fathom-analyze/spike/s5           # packets, arm A, blinded corpus
python3 -m recommender.narrative score \
        --spike crates/fathom-analyze/spike/s5 \
        --report benchmarks/reports/s5-narrative-polish.json
python3 -m recommender.narrative score … --check         # the recorded report is what this run gets
```

`--deltas` is a directory of `fathom analyze --json` output, one file per episode; producing it is the
only IO the spike does outside the store (`fathom analyze <ep> --json` per episode), and it is cached
on purpose so `--check` and the contract test re-run the whole experiment with no binary, no network
and no clock. `collect` is deliberately split from `score`: arm A is generated by code, arms B and C
were generated by a model and are *recorded artefacts* under `spike/s5/arms/`, and the split is what
keeps "the harness re-ran" different from "the model spoke again".

Cost and latency, the two numbers this environment cannot measure honestly, are labelled at every
level instead of being quietly included:

* **arm A**: wall-clock measured here, per episode, render-only (matching the way `e2.10`'s card
  budget is written), and free of any token cost;
* **arms B/C**: token counts measured from recorded characters, cost and latency **modelled** at the
  reference price band in `REFERENCE` from the recorded provenance — no provider SDK or API key was
  reachable from the spike sandbox, so nothing here is an invoice or a wall-clock. The concept doc
  makes that an explicit gate on any future ship decision rather than pretending it was measured.
"""

from __future__ import annotations

import argparse
import gzip
import json
import os
import subprocess
import sys
import time
from typing import Any

from . import template as template_mod
from .audit import Support, audit
from .corpus import select
from .packet import build_packet, render_index, sha
from .panel import aggregate, cross_check, dump, make_blinding, normalise, validate

SPIKE_ID = "s5"
TICKET = "reco-6p8"
ARMS = {"template": "A?", "polish": "B?", "why": "C?"}
RECORDED_ARMS = ("polish", "why")
RESAMPLED_FOR_DETERMINISM = 6

#: reference price band, US$ per million tokens, and a decode rate — a placeholder to be replaced by
#: the price of whatever provider the opt-in would actually call. Kept in one place so the report can
#: never imply it measured a bill.
REFERENCE = {"usd_per_mtok_in": 3.0, "usd_per_mtok_out": 15.0, "tokens_per_second": 55.0,
             "time_to_first_token_s": 0.4, "chars_per_token": 4.0}

#: what the spike concluded, recorded here so the report and the decision issue cannot drift
VERDICT = {
    "decision": "ship-nothing-yet: arm A is e4.7's narrative; the net-llm polish seam stays unwired "
                "(no consumer, no flag, no code path) until every gate in the decision issue is met",
    "decision_issue": "reco-nv0",
    "decided": "2026-10-19",
    "why": "usefulness rose (2.23 -> 4.40) while trustworthiness fell (4.667 -> 4.000) and coverage "
           "halved (0.61 -> 0.32); ADR-001 §8 non-goal 6 asks for a win on trust AND usefulness with "
           "hallucinations at zero, and the readability gap the polish arm closes is a template bug "
           "worth fixing in the template - see docs/concepts/narrative-polish.md §7",
    "gates": [
        "hallucinated claims at zero on >=100 episodes and >=3 repositories, with an adversarial arm",
        "a measured win on trustworthiness as well as usefulness, from three human reviewers",
        "cost and latency measured against a real provider, and a byte-identical offline fallback",
        "byte-stable exports (e5.7) survive a polished narrative, or that guarantee is dropped on purpose",
        "citation preservation enforced by the renderer, not instructed to the model",
    ],
}


