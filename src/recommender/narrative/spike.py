def tokens(chars: int) -> int:
    return int(round(chars / REFERENCE["chars_per_token"]))


def cost_of(in_chars: int, out_chars: int) -> dict[str, Any]:
    tin, tout = tokens(in_chars), tokens(out_chars)
    modelled = (tin * REFERENCE["usd_per_mtok_in"] + tout * REFERENCE["usd_per_mtok_out"]) / 1e6
    return {
        "tokens_in_estimate": tin, "tokens_out_estimate": tout,
        "usd_modelled": round(modelled, 6),
        "seconds_modelled": round(REFERENCE["time_to_first_token_s"] + tout / REFERENCE["tokens_per_second"], 2),
        "basis": "modelled: token counts estimated at 4 chars/token from recorded characters, priced "
                 "at REFERENCE — no API key was reachable, so this is not an invoice and not a wall-clock",
    }


def score(spike_dir: str) -> dict[str, Any]:
    record = read_json(os.path.join(spike_dir, "selection.json"))
    blinding = read_json(os.path.join(spike_dir, "blinding-key.pending.json"))
    episodes = [e["episode"] for e in record["episodes"]]
    packets = {e: read_json(os.path.join(spike_dir, "packets", f"{e}.json")) for e in episodes}
    prov_path = os.path.join(spike_dir, "arms", "provenance.json")
    provenance = read_json(prov_path) if os.path.exists(prov_path) else {}

    supports = {e: Support(packets[e]) for e in episodes}
    per_episode: list[dict[str, Any]] = []
    findings_by_arm: dict[str, dict[str, list[str]]] = {a: {} for a in ("template", "polish", "why")}
    totals: dict[str, dict[str, Any]] = {}
    for arm in ("template", "polish", "why"):
        totals[arm] = {"claims": 0, "words": 0, "hallucinated_claims_tolerant": 0,
                       "hallucinated_claims_strict": 0, "uncited": 0, "inference": 0,
                       "by_kind": {}, "episodes": 0, "chars": 0}

    index_chars = sum(len(render_index(packets[e])) for e in episodes)
    for eid in episodes:
        row: dict[str, Any] = {"episode": eid, "subject": packets[eid]["episode"]["subject"], "arms": {}}
        for arm in ("template", "polish", "why"):
            text = arm_text(spike_dir, eid, arm)
            if text is None:
                continue
            started = time.perf_counter()
            result = audit(text, supports[eid])
            if arm == "template":
                elapsed_ms = round((time.perf_counter() - started) * 1000, 3)
                row["arms"][arm] = _arm_row(result, measured_ms=elapsed_ms, out_chars=len(text),
                                            in_chars=len(render_index(packets[eid])))
            else:
                row["arms"][arm] = _arm_row(result, out_chars=len(text),
                                            in_chars=len(render_index(packets[eid])) + len(arm_text(spike_dir, eid, "template") or ""))
            tally = totals[arm]
            tally["episodes"] += 1
            tally["claims"] += result["claims"]
            tally["words"] += result["words"]
            tally["chars"] += len(text)
            tally["hallucinated_claims_tolerant"] += result["tolerant"]["hallucinated_claims"]
            tally["hallucinated_claims_strict"] += result["strict"]["hallucinated_claims"]
            tally["uncited"] += result["tolerant"]["by_kind"].get("uncited", 0)
            tally["inference"] += result["tolerant"]["by_kind"].get("inference", 0)
            for kind, n in result["tolerant"]["by_kind"].items():
                tally["by_kind"][kind] = tally["by_kind"].get(kind, 0) + n
            for f in result["tolerant"]["findings"]:
                findings_by_arm[arm].setdefault(eid, []).append(f["claim"] + " — " + f["detail"])
            row["arms"][arm]["hallucinations_detail"] = [
                f for f in result["tolerant"]["findings"]
                if f["kind"] in ("invented_number", "invented_path", "invented_identifier",
                                 "contradiction", "fabricated_rationale")]
        per_episode.append(row)

    panel_path = os.path.join(spike_dir, "panel")
    scorecards = [read_json(os.path.join(panel_path, n)) for n in sorted(os.listdir(panel_path))
                  if n.endswith(".json")] if os.path.isdir(panel_path) else []
    digests = blinded_corpus(spike_dir, packets, blinding, write=False)
    problems = validate(scorecards, blinding, digests) if scorecards else ["no panel scorecards on disk"]
    panel_report = aggregate(scorecards, blinding) if scorecards else {}
    if panel_report:
        panel_report["cross_check"] = cross_check(panel_report.get("flags", {}), findings_by_arm)
        panel_report["integrity_problems"] = problems

    determinism = _determinism(spike_dir, packets)
    for arm in ("polish", "why"):
        costs = [r["arms"][arm]["cost"] for r in per_episode if arm in r["arms"]]
        totals[arm]["cost_per_episode_usd_modelled"] = round(
            sum(c["usd_modelled"] for c in costs) / max(1, len(costs)), 6)
        totals[arm]["seconds_per_episode_modelled"] = round(
            sum(c["seconds_modelled"] for c in costs) / max(1, len(costs)), 2)
    totals["template"]["ms_per_episode_measured"] = round(
        sum(r["arms"]["template"]["ms_measured"] for r in per_episode if "template" in r["arms"])
        / max(1, sum(1 for r in per_episode if "template" in r["arms"])), 3)
    totals["_evidence_packet_chars"] = index_chars

    hallucinations = []
    for row in per_episode:
        for arm, data in row["arms"].items():
            if data["tolerant"]["hallucinated_claims"]:
                hallucinations.append({"episode": row["episode"], "arm": arm,
                                       "count": data["tolerant"]["hallucinated_claims"],
                                       "detail": data["hallucinations_detail"]})

    return {
        "spike": SPIKE_ID, "ticket": TICKET,
        "question": "does an optional LLM narrative polish beat the deterministic template on "
                    "accuracy, usefulness and trustworthiness, with hallucinations held at zero",
        "corpus": record,
        "arms": totals,
        "per_episode": per_episode,
        "hallucinations": hallucinations,
        "panel": panel_report,
        "determinism": determinism,
        "reference_pricing": REFERENCE,
        "llm_arm_provenance": provenance,
        "verdict": VERDICT,
    }


def _arm_row(result: dict[str, Any], out_chars: int, in_chars: int,
             measured_ms: float | None = None) -> dict[str, Any]:
    row = {k: v for k, v in result.items()}
    for tier in ("strict", "tolerant"):
        row[tier] = {k: v for k, v in result[tier].items() if k != "findings"}
    row["cost"] = cost_of(in_chars, out_chars)
    if measured_ms is not None:
        row["ms_measured"] = measured_ms
    return row


def _determinism(spike_dir: str, packets: dict[str, Any]) -> dict[str, Any]:
    """Arm A twice in-process and once in a fresh process; arm B twice from recorded resamples."""
    same = drift = 0
    for eid, packet in packets.items():
        first = template_mod.render(packet)
        second = template_mod.render(packet)
        on_disk = arm_text(spike_dir, eid, "template")
        if first == second and (on_disk is None or first == on_disk):
            same += 1
        else:
            drift += 1
    subprocess_check = _subprocess_render(spike_dir)
    resampled: list[dict[str, Any]] = []
    for eid in list(packets)[:RESAMPLED_FOR_DETERMINISM]:
        once, twice = arm_text(spike_dir, eid, "polish"), arm_text(spike_dir, eid, "polish", "2")
        if once is None or twice is None:
            continue
        a, b = set(_figures(once)), set(_figures(twice))
        resampled.append({"episode": eid, "byte_identical": once == twice,
                          "figures_only_in_first": sorted(a - b), "figures_only_in_second": sorted(b - a),
                          "words_first": len(once.split()), "words_second": len(twice.split())})
    return {
        "template": {"episodes_reproduced": same, "episodes_drifted": drift,
                     "fresh_process_matches": subprocess_check,
                     "note": "arm A is a byte function of the delta document: no clock, no locale, no "
                             "terminal probe, so a golden test can bless it"},
        "polish_resampled": resampled,
        "polish_note": f"{len(resampled)} episodes sampled twice from the model; identical bytes are the "
                       "absence of drift in one sample, not a determinism guarantee — the second call "
                       "of a real provider is what a ship decision needs and no key was reachable here",
    }


def _subprocess_render(spike_dir: str) -> bool | None:
    """Re-render one packet in a fresh interpreter and compare digests — the claim a golden test makes."""
    packets = sorted(os.listdir(os.path.join(spike_dir, "packets")))
    if not packets:
        return None
    target = os.path.join(spike_dir, "packets", packets[0])
    res = subprocess.run([sys.executable, "-m", "recommender.narrative", "template", "--packet", target],
                         capture_output=True, text=True)
    if res.returncode != 0:
        return False
    stored = arm_text(spike_dir, packets[0][:-5], "template")
    return res.stdout == stored


def _figures(text: str) -> list[str]:
    import re
    return re.findall(r"\d[\d,.]*|/[\w./-]+", text)


