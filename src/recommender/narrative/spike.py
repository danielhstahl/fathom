def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python3 -m recommender.narrative")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("collect", help="select the 20 episodes, build packets, render arm A")
    p.add_argument("--deltas", required=True)
    p.add_argument("--spike", required=True)
    p.add_argument("--repo", default=".")
    p.add_argument("--seed", default="s5-blinding-v1")

    p = sub.add_parser("template", help="render arm A for one packet (used by the determinism check)")
    p.add_argument("--packet", required=True)

    p = sub.add_parser("evidence", help="print the citation index for one packet")
    p.add_argument("--packet", required=True)

    p = sub.add_parser("audit", help="audit one narrative file against one packet")
    p.add_argument("--packet", required=True)
    p.add_argument("--text", required=True)

    p = sub.add_parser("blind", help="write the blinded corpus reviewers score")
    p.add_argument("--spike", required=True)
    p.add_argument("--seed", default="s5-blinding-v1")

    p = sub.add_parser("score", help="audit every arm, score the panel, write the report")
    p.add_argument("--spike", required=True)
    p.add_argument("--report", required=True)
    p.add_argument("--check", action="store_true")

    args = parser.parse_args(argv)
    if args.cmd == "collect":
        out = collect(args.deltas, args.spike, args.repo, args.seed)
        print(f"selected {len(out['packets'])} episodes into {args.spike}")
        return 0
    if args.cmd == "template":
        sys.stdout.write(template_mod.render(read_json(args.packet)))
        return 0
    if args.cmd == "evidence":
        sys.stdout.write(render_index(read_json(args.packet)))
        return 0
    if args.cmd == "audit":
        with open(args.text) as fh:
            text = fh.read()
        result = audit(text, Support(read_json(args.packet)))
        print(json.dumps({t: {k: v for k, v in result[t].items() if k != "findings"}
                          for t in ("strict", "tolerant")} | {"claims": result["claims"]},
                         indent=1, sort_keys=True))
        for tier in ("strict", "tolerant"):
            for f in result[tier]["findings"]:
                print(f"{tier:9} {f['kind']:24} {f['detail']} :: {f['claim'][:90]}")
        return 0
    if args.cmd == "blind":
        record = read_json(os.path.join(args.spike, "selection.json"))
        episodes = [e["episode"] for e in record["episodes"]]
        packets = {e: read_json(os.path.join(args.spike, "packets", f"{e}.json")) for e in episodes}
        blinding = make_blinding(episodes, {a: a for a in ("template", "polish", "why")}, args.seed)
        digests = blinded_corpus(args.spike, packets, blinding)
        joined = sha("".join(digests[k] for k in sorted(digests)))
        print(json.dumps({"files": len(digests), "corpus_digest": joined,
                          "note": "score this text, then write the key"}, indent=1, sort_keys=True))
        return 0
    if args.cmd == "score":
        report = score(args.spike)
        if args.check:
            if not os.path.exists(args.report):
                print(f"--check: no recorded report at {args.report}", file=sys.stderr)
                return 1
            stored = read_json(args.report)
            diffs = _diff(stored, report)
            if diffs:
                print(f"--check: {len(diffs)} recorded figure(s) no longer reproduce:", file=sys.stderr)
                for d in diffs[:40]:
                    print("  " + d, file=sys.stderr)
                return 1
            print(f"--check: {args.report} reproduces")
            return 0
        write_json(args.report, report)
        _print(report)
        return 0
    return 2


def _diff(stored: Any, fresh: Any, path: str = "") -> list[str]:
    """Structural diff that ignores the volatile fields a re-run legitimately changes."""
    skip = {"ms_measured", "seconds_modelled", "usd_modelled", "tokens_in_estimate",
            "tokens_out_estimate", "ms_per_episode_measured", "seconds_per_episode_modelled",
            "cost_per_episode_usd_modelled", "head", "note", "basis", "why", "decision_issue",
            "unconfirmed"}
    if isinstance(stored, dict) and isinstance(fresh, dict):
        out: list[str] = []
        for k in sorted(set(stored) | set(fresh)):
            if k in skip or k not in stored or k not in fresh:
                continue
            out.extend(_diff(stored[k], fresh[k], f"{path}/{k}"))
        return out
    if isinstance(stored, list) and isinstance(fresh, list):
        if len(stored) != len(fresh):
            return [f"{path}: length {len(stored)} -> {len(fresh)}"]
        out = []
        for i, (a, b) in enumerate(zip(stored, fresh)):
            out.extend(_diff(a, b, f"{path}[{i}]"))
        return out
    return [] if stored == fresh else [f"{path}: {stored!r} -> {fresh!r}"]


def _print(report: dict[str, Any]) -> None:
    print(f"spike {report['spike']} ({report['ticket']}) — {report['corpus']['rule']['selected']} episodes")
    for arm, data in report["arms"].items():
        if not isinstance(data, dict) or "claims" not in data:
            continue
        print(f"  {arm:9} claims={data['claims']:4} halluc(tolerant)={data['hallucinated_claims_tolerant']:3} "
              f"halluc(strict)={data['hallucinated_claims_strict']:3} uncited={data['uncited']:3} "
              f"inference={data['inference']:3}")
    panel = report.get("panel", {})
    if panel.get("pooled"):
        for arm, crits in sorted(panel["pooled"].items()):
            print(f"  panel {arm:9} " + " ".join(f"{c}={crits[c]}" for c in ("accuracy", "usefulness", "trustworthiness")))
    if panel.get("integrity_problems"):
        print("  PANEL INTEGRITY PROBLEMS:")
        for problem in panel["integrity_problems"]:
            print("   - " + problem)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
