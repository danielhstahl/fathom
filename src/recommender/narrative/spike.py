def load_deltas(directory: str) -> list[dict[str, Any]]:
    out = []
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".json"):
            continue
        with open(os.path.join(directory, name)) as fh:
            out.append(json.load(fh))
    return out


def commit_subjects(deltas: list[dict[str, Any]], repo: str | None) -> dict[str, str]:
    """`oid -> subject` for every member commit, straight from git (the runner is the IO layer)."""
    if not repo:
        return {}
    subs: dict[str, str] = {}
    for delta in deltas:
        for oid in (delta.get("episode", {}).get("members") or []):
            if oid in subs:
                continue
            res = subprocess.run(["git", "-C", repo, "show", "-s", "--format=%s", oid],
                                 capture_output=True, text=True)
            if res.returncode == 0:
                subs[oid] = res.stdout.strip()
    return subs


def ensure_dir(path: str) -> str:
    os.makedirs(path, exist_ok=True)
    return path


def write_json(path: str, obj: Any) -> None:
    ensure_dir(os.path.dirname(path))
    with open(path, "w") as fh:
        json.dump(obj, fh, indent=1, sort_keys=True, ensure_ascii=False)
        fh.write("\n")


def read_json(path: str) -> Any:
    with open(path) as fh:
        return json.load(fh)


def read_json_gz(path: str) -> Any:
    """A gzipped recorded delta document — the corpus the selection rule re-derives from in CI."""
    import gzip
    with gzip.open(path, "rt") as fh:
        return json.load(fh)


def collect(deltas_dir: str, spike_dir: str, repo: str | None, seed: str) -> dict[str, Any]:
    deltas = load_deltas(deltas_dir)
    picked = select(deltas)
    episodes = picked["_deltas"]
    subjects = commit_subjects(episodes, repo)

    os.makedirs(spike_dir, exist_ok=True)
    record = {k: v for k, v in picked.items() if k != "_deltas"}
    record["provenance"] = {
        "corpus": "this repository's own history, indexed by `fathom index` at the HEAD recorded below",
        "head": _head(repo or "."),
        "episodes": len(episodes),
        "note": "real agent-authored commits; the annotator is the project author, which §"
                "threats of the concept doc owns up to",
    }
    write_json(os.path.join(spike_dir, "selection.json"), record)

    packets: dict[str, Any] = {}
    for delta in episodes:
        eid = delta["episode"]["id"]
        packet = build_packet(delta, subjects)
        packets[eid] = packet
        write_json(os.path.join(spike_dir, "packets", f"{eid}.json"), packet)
        ensure_dir(os.path.join(spike_dir, "evidence"))
        with open(os.path.join(spike_dir, "evidence", f"{eid}.txt"), "w") as fh:
            fh.write(render_index(packet))
        ensure_dir(os.path.join(spike_dir, "arms", eid))
        with open(os.path.join(spike_dir, "arms", eid, "template.md"), "w") as fh:
            fh.write(template_mod.render(packet))

    blinded = make_blinding(list(packets), {a: a for a in ("template", "polish", "why")}, seed)
    write_json(os.path.join(spike_dir, "blinding-key.pending.json"), blinded)
    return {"packets": packets, "record": record, "blinding": blinded}


def _head(repo: str) -> str:
    try:
        return subprocess.run(["git", "-C", repo, "rev-parse", "HEAD"], capture_output=True,
                              text=True).stdout.strip()
    except OSError:
        return ""


# ---------------------------------------------------------------------------------------------
# arms on disk
# ---------------------------------------------------------------------------------------------

def arm_text(spike_dir: str, episode: str, arm: str, which: str = "") -> str | None:
    path = os.path.join(spike_dir, "arms", episode, f"{arm}{which}.md")
    if not os.path.exists(path):
        return None
    with open(path) as fh:
        return fh.read()


def blinded_corpus(spike_dir: str, packets: dict[str, Any], blinding: dict[str, Any],
                   write: bool = True) -> dict[str, str]:
    """The text a reviewer sees: `<episode>-<label>.md`, no arm names anywhere."""
    digests: dict[str, str] = {}
    for eid, packet in packets.items():
        for label, arm in blinding["key"][eid].items():
            text = arm_text(spike_dir, eid, arm)
            if text is None:
                continue
            body = (f"# Episode {eid} — narrative {label}\n\n"
                    f"{packet['episode']['subject']}\n\n---\n\n{text}")
            digests[f"{eid}-{label}"] = sha(body)
            if write:
                path = os.path.join(spike_dir, "blinded", f"{eid}-{label}.md")
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w") as fh:
                    fh.write(body)
    return digests


