"""Generated-file churn: the diff a generator wrote, not the one a person wrote.

`e0.9` already knows a path is generated (`*.pb.go`, `dist/`, `*_generated.rs`, a protoc
banner read by `e2.1`'s markers). Knowing that is not enough to fold the change, and the
difference matters: a generated file can move for four reasons and only three of them are
noise.

| kind | what the diff looks like | folded? | why |
|---|---|---|---|
| `stamp` | only generator stamps moved — a `protoc-gen-go v1.36.1` line, a `generated at` timestamp, a content hash | yes | nothing the reviewer could act on changed |
| `resort` | the same lines, in a different order (a sorted index, a rebuilt manifest, a map serialised with new tie-breaking) | yes | the content set is provably unchanged: the multisets are equal |
| `regen` | a bulk rewrite of a file no hand-written source in the episode explains | yes | this is what re-running a generator looks like, and the raw hunks are re-derivable from whatever generated them |
| `hand-edit` | a *small* change inside a generated file that is neither a stamp nor a re-order | **no** | either somebody edited a generated file (a finding, `e4.3`'s) or the generator emits only this region — the two are indistinguishable from here, so the change stays on screen |

The fourth row is the one that makes this detector trustworthy. A rule that folded
generated files by bulk alone would fold a hand edit to `api.pb.go` — the single most
expensive mistake available to a noise suppressor, because it is invisible until the next
`protoc` run silently reverts someone's fix. So the bulk rule needs a floor, and anything
under it says "I cannot tell who wrote this" and stays visible with that sentence.

Nothing here pretends to know *which* generator ran. `generator_hint` is the marker text
`e2.1` read (`protoc-gen-go`, `openapi-generator`, `jest snapshot`), and it is printed as
evidence, not as a claim about causation.

The `history` input is caller-supplied on purpose: this package is pure (ADR-002 §4.5) and
does not read the store, so a repeated-regeneration count arrives as a number and is used
only as corroboration in the evidence line — never as a gate. A gate the caller can lie to
is not a gate.
"""

from __future__ import annotations

import re
from collections import Counter
from dataclasses import dataclass, field

from recommender.taxonomy import classes as C

from . import norm

#: The claims. Only the first three suppress.
CHURN = "generated-churn"
HAND_EDIT = "hand-edit-suspected"
NOT_GENERATED = "not-generated"
NO_CHANGE = "no-change"

#: A bulk rewrite: this share of the file's lines, and at least this many of them, before
#"`regen` may be said. Below it the answer is `hand-edit` and the change stays visible.
BULK_RATIO = 0.6
BULK_MIN_LINES = 40

#: A re-order needs at least this many lines on both sides before the multiset equality is
#: worth reporting; two lines swapping is a coincidence, three hundred is a rebuild.
RESORT_MIN_LINES = 3

#: The stamp vocabulary: lines a generator writes about itself, and nothing else.
STAMP_PATTERNS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("generator banner", re.compile(
        r"(?:^|\s)(?:@generated|generated by|auto-?generated|code generated by|"
        r"do not edit|do not hand-?edit)", re.I)),
    ("version stamp", re.compile(
        r"(?:protoc-gen-\w+|protoc|thrift|flatbuffers|openapi-generator|swagger-codegen|"
        r"json-schema-to-typescript|buildifier|webpack|vite|rollup)\S*.{0,24}v?\d+\.\d+",
        re.I)),
    ("timestamp", re.compile(
        r"(?:generated(?:_at| on|ed at)?|updated(?:_at| on)?|created(?:_at| on)?|"
        r"last modified|timestamp|date)\s*[:=]", re.I)),
    ("content hash", re.compile(
        r"(?:sha\d+|md5|checksum|integrity|digest|hash)\s*[:=]", re.I)),
    ("build stamp", re.compile(
        r"(?:commit|revision|build|source revision|git sha)\s*[:=]\s*[0-9a-f]{6,}", re.I)),
)

#: Markers whose presence makes "generated" a strong statement, mirrored from the `e2.1`
#: marker table's decisive set. Read as a string check, not a re-implementation.
STRONG_BANDS = ("confirmed", "likely")


@dataclass
class Generated:
    """One generated file's verdict, with the receipts."""

    path: str
    claim: str = NOT_GENERATED
    kind: str = ""                                # stamp | resort | regen | hand-edit
    path_class: str = ""
    band: str = ""
    generator_hint: str = ""
    changed_lines: int = 0
    stamp_lines: int = 0
    file_lines: int = 0
    history: int = 0
    history_window: int = 0
    inputs_moved: list[str] = field(default_factory=list)
    samples: list[str] = field(default_factory=list)
    evidence: list[str] = field(default_factory=list)

    @property
    def is_churn(self) -> bool:
        return self.claim == CHURN

    @property
    def bulk_ratio(self) -> float:
        if not self.file_lines:
            return 0.0
        return round(min(1.0, self.changed_lines / self.file_lines), 3)

    @property
    def reason(self) -> str:
        if self.claim == CHURN:
            return "%s in a generated file: %s" % (self.kind, "; ".join(self.evidence[:1]))
        if self.claim == HAND_EDIT:
            return ("a small change inside a generated file that is neither a stamp nor a "
                    "re-order: cannot tell a hand edit from a partial regeneration, so it is "
                    "not folded")
        if self.claim == NO_CHANGE:
            return "the generated file's two revisions are identical"
        return "the path is not generated, so generated-churn does not speak for it"

    def as_dict(self) -> dict:
        return {"path": self.path, "claim": self.claim, "kind": self.kind,
                "class": self.path_class, "band": self.band, "reason": self.reason,
                "generator": self.generator_hint, "changed_lines": self.changed_lines,
                "file_lines": self.file_lines, "bulk_ratio": self.bulk_ratio,
                "stamp_lines": self.stamp_lines, "history": self.history,
                "inputs_moved": sorted(self.inputs_moved), "samples": list(self.samples[:4]),
                "evidence": list(self.evidence)}


def inspect(path: str, before: str | None, after: str | None, *, path_class: str = "",
            band: str = "", generator_hint: str = "", change_type: str = "modified",
            history: int = 0, history_window: int = 0,
            inputs_moved: list[str] | None = None) -> Generated:
    """Decide whether one generated file's diff is churn. Pure: text in, verdict out."""
    verdict = Generated(path=path, path_class=path_class, band=band,
                        generator_hint=generator_hint, history=history,
                        history_window=history_window, inputs_moved=list(inputs_moved or ()))
    if change_type in ("added", "deleted") or before is None or after is None:
        verdict.evidence.append("both revisions are needed to call a change regeneration; "
                               "this pair is a %s" % change_type)
        return verdict
    if not _is_generated(path_class, generator_hint, band):
        verdict.claim = NOT_GENERATED
        verdict.evidence.append("class %s, band %s, marker %s: nothing here says generated"
                               % (path_class or "—", band or "—", generator_hint or "—"))
        return verdict
    if before == after:
        verdict.claim = NO_CHANGE
        return verdict

    removed, added = norm.changed_lines(before, after)
    verdict.file_lines = norm.line_count(after)
    verdict.changed_lines = len(removed) + len(added)
    if not removed and not added:
        verdict.claim = NO_CHANGE
        return verdict

    stamp_removed = [line for line in removed if _is_stamp(line)]
    stamp_added = [line for line in added if _is_stamp(line)]
    verdict.stamp_lines = len(stamp_removed) + len(stamp_added)
    verdict.samples = _pair_samples(removed, added)

    # 1. stamps only.
    if verdict.stamp_lines == verdict.changed_lines:
        return _churn(verdict, "stamp",
                      ["all %d changed line(s) are generator stamps (%s)"
                       % (verdict.changed_lines, _stamp_kinds(removed, added))])

    # 2. a re-order: same lines, different order.
    if _is_resort(removed, added):
        return _churn(verdict, "resort",
                      ["the same %d line(s) before and after, in a different order: nothing "
                       "was added or removed" % min(len(removed), len(added))])

    # 3. a bulk regeneration.
    ratio = verdict.bulk_ratio
    if verdict.changed_lines >= BULK_MIN_LINES and ratio >= BULK_RATIO:
        lines = ["%.0f%% of the file (%d of %d lines) was rewritten"
                 % (ratio * 100, verdict.changed_lines, verdict.file_lines)]
        if verdict.band in STRONG_BANDS:
            lines.append("the file is %s-generated (%s)"
                         % (verdict.band, verdict.generator_hint or "by a committed generator"))
        if verdict.inputs_moved:
            lines.append("the episode also changed %d hand-written file(s): %s"
                         % (len(verdict.inputs_moved), ", ".join(sorted(verdict.inputs_moved)[:3])))
        else:
            lines.append("no hand-written file moved in this episode: this is a regeneration "
                         "on its own")
        return _churn(verdict, "regen", lines)

    # 4. nothing folded.
    verdict.claim = HAND_EDIT
    verdict.evidence.append(
        "%d of %d lines changed (%.0f%%), which is below the %d-line / %.0f%% bulk floor: "
        "a small edit inside a generated file"
        % (verdict.changed_lines, verdict.file_lines, ratio * 100, BULK_MIN_LINES,
           BULK_RATIO * 100))
    verdict.evidence.extend("line %s" % line for line in verdict.samples[:4])
    if verdict.history >= 2 and verdict.history_window:
        verdict.evidence.append("touched in %d of the last %d episodes"
                               % (verdict.history, verdict.history_window))
    return verdict


def _is_generated(path_class: str, hint: str, band: str) -> bool:
    if path_class == C.PathClass.GENERATED:
        return True
    return bool(hint) and band in STRONG_BANDS


def _is_stamp(line: str) -> bool:
    return any(pattern.search(line) for _kind, pattern in STAMP_PATTERNS)


def _stamp_kinds(removed: list[str], added: list[str]) -> str:
    kinds: list[str] = []
    for line in (*removed, *added):
        for kind, pattern in STAMP_PATTERNS:
            if pattern.search(line) and kind not in kinds:
                kinds.append(kind)
    return ", ".join(kinds) or "generator stamps"


def _is_resort(removed: list[str], added: list[str]) -> bool:
    if min(len(removed), len(added)) < RESORT_MIN_LINES:
        return False
    if abs(len(removed) - len(added)) > max(1, len(added) // 10):
        return False
    return Counter(_collapse(line) for line in removed) == \
        Counter(_collapse(line) for line in added)


def _collapse(line: str) -> str:
    return " ".join(line.split())


def _pair_samples(removed: list[str], added: list[str]) -> list[str]:
    out: list[str] = []
    for old, new in zip(removed[:4], added[:4]):
        out.append("- %s" % old[:78])
        out.append("+ %s" % new[:78])
    if not out:
        out = ["- %s" % line[:78] for line in removed[:4]]
        out += ["+ %s" % line[:78] for line in added[:4]]
    return out


def _churn(verdict: Generated, kind: str, evidence: list[str]) -> Generated:
    verdict.claim = CHURN
    verdict.kind = kind
    verdict.evidence = evidence
    if verdict.history >= 2 and verdict.history_window:
        verdict.evidence.append("regenerated in %d of the last %d episodes (corroboration "
                                "only: history never gates this rule)"
                                % (verdict.history, verdict.history_window))
    return verdict
