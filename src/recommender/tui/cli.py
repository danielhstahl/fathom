"""`fathom tui` — the verb surface over ADR-006's data.

This is not the TUI; it is the *checkable* surface the TUI is built against. `e1.5`
implements the shell, `e5.4` the palette and overrides, and `e7.5` the docs-site
cheatsheet; all three read this table instead of restating it, which is the only way the
help overlay, the cheatsheet and ADR-006 stay honest with each other.

    fathom tui views                      the view inventory, as a table
    fathom tui keys [--cheatsheet]         the keymap, or the printable cheatsheet
    fathom tui layout <view> [-c -r]       render a view at a size (default: documented)
    fathom tui fit <view> <cols>x<rows>    what the degradation ladder does at that size
    fathom tui press "<keys>" [--view]     resolve a published key sequence
    fathom tui tasks                       the three canonical tasks, with every key
    fathom tui matrix                      the e5.5 layout matrix
    fathom tui palette                     every palette entry with its binding
    fathom tui conflicts [--toml PATH]     load-time keymap conflict detection
    fathom tui probe [--machine]           what the terminal can actually deliver (pty)
    fathom tui doc --check | --write       the ADR's generated blocks
"""

from __future__ import annotations

import argparse
import sys

from . import docs as D
from . import keymap as K
from . import render as R
from .views import LAYOUT_MATRIX, VIEWS


def _view(name: str):
    for v in VIEWS:
        if v.id == name or v.key == name:
            return v
    raise SystemExit("unknown view %r (known: %s)" % (name, ", ".join(v.id for v in VIEWS)))


def _cols_rows(spec: str) -> tuple[int, int]:
    try:
        c, r = spec.lower().split("x")
        return int(c), int(r)
    except ValueError:
        raise SystemExit("size must look like 80x24")


def cmd_views(_args) -> int:
    print(D.view_inventory())
    print()
    print(D.sizes())
    return 0


def cmd_keys(args) -> int:
    if args.cheatsheet:
        print(cheatsheet())
        return 0
    print(D.keymap_table())
    return 0


def cheatsheet() -> str:
    """The generated cheatsheet (`e7.5` publishes this; it is not retyped)."""
    out = ["# Fathom keys", "",
           "Generated by `fathom tui keys --cheatsheet`. Every action is either listed "
           "here or reachable from `,`.", ""]
    for scope, title in (("view", "Views"), ("overlay", "Overlays"),
                         ("motion", "Motion (every list, every view)"),
                         ("frame", "Panes, drill, tabs"), ("review", "Review"),
                         ("scope", "Scope and comparison"),
                         ("view", "View-local"), ("index", "Index and screen")):
        rows = []
        for action_id, act in sorted(K.ACTIONS.items()):
            if act.scope != scope:
                continue
            keys = sorted({k.split(":", 1)[1]
                           for k in K.binding_index().get(action_id, [])})
            if not keys:
                continue
            modes = "" if act.modes == ("global",) else "  *(%s)*" % ",".join(act.modes)
            rows.append("- `%s` — %s%s" % ("` `".join(keys), act.title, modes))
        if rows:
            out += ["## " + title, ""] + rows + [""]
    out += ["## Reserved for the user", "",
            "Fathom leaves these alone, so `keys.overrides.<mode>.<key>` may claim them:", ""]
    out += ["- `%s` — %s *(free %s)*" % (chord, why, where)
            for chord, why, where in K.RESERVED_FOR_USER]
    out += ["", "## The terminal will not deliver these", ""]
    out += ["- `%s` — %s" % (c, why) for c, _byte, why in K.TERMINAL_UNUSABLE]
    return "\n".join(out)


def cmd_layout(args) -> int:
    view = _view(args.view)
    cols, rows = args.cols or view.ideal_cols, args.rows or view.ideal_rows
    for line in R.draw(view, cols, rows):
        print(line)
    return 0


def cmd_fit(args) -> int:
    view = _view(args.view)
    cols, rows = _cols_rows(args.size)
    f = R.fit(view, cols, rows)
    print("view      %s" % view.id)
    print("terminal  %d×%d" % (cols, rows))
    print("documented %d×%d · min %d×%d · floor %d×%d · refuses below %d×%d"
          % (view.ideal_cols, view.ideal_rows, R.min_cols_view(view), view.min_rows,
             R.floor_cols(view), R.floor_rows(view), R.refuse_below_cols(view),
             R.refuse_below_rows(view)))
    print("state     %s" % f.state)
    if not f.applied:
        print("  (nothing dropped: the documented layout fits)")
    else:
        by_id = {s.id: s for s in list(R.LADDER) + [R.FALLBACK, R.REFUSED]}
        for applied in f.applied:
            print("  - %s: %s" % (applied, by_id[applied].what))
    return 0


def cmd_press(args) -> int:
    steps = K.press(args.sequence, view=args.view, interaction=args.mode)
    for s in steps:
        print("%-10s via %-28s -> %s" % (s["chord"], s["chain"], s["action"]))
    return 0


def cmd_tasks(_args) -> int:
    for t in K.TASKS:
        print("== %s — %s" % (t.id, t.name))
        print("   %s" % t.asks)
        print("   %s" % "  then  ".join(t.steps[i].key for i in range(len(t.steps))))
        for i, s in enumerate(t.steps, 1):
            print("   %d. %-10s %-18s %s" % (i, s.key, s.action, s.effect))
        print("   note: %s\n" % t.note)
    return 0


def cmd_matrix(_args) -> int:
    print(D.layout_matrix())
    print()
    print(D.layout_matrix_steps())
    return 0


def cmd_palette(_args) -> int:
    print(D.palette_dump())
    holes = K.unbound_actions()
    if holes:
        print("\nkeyboard-reachability holes (bound nowhere, absent from the palette):")
        for h in holes:
            print("  %s" % h)
        return 1
    return 0


def cmd_conflicts(args) -> int:
    overrides: dict[str, dict[str, str]] = {}
    if args.toml:
        overrides = _overrides_from_toml(args.toml)
    for item in args.set or []:
        mode, rest = item.split(".", 1)
        chord, action = rest.split("=", 1)
        overrides.setdefault(mode, {})[chord] = action
    problems = K.conflicts(overrides)
    if not overrides:
        print("no overrides given; the shipped table has no conflicts: %s"
              % (not K.conflicts(K.DEFAULTS)))
        return 0
    if problems:
        for p in problems:
            print("conflict: %s" % p)
        return 1
    print("%d override(s) merge cleanly." % sum(len(v) for v in overrides.values()))
    return 0


def _overrides_from_toml(path: str) -> dict[str, dict[str, str]]:
    try:
        import tomllib
    except ImportError:                                       # pragma: no cover
        raise SystemExit("tomllib is required to read %s" % path)
    with open(path, "rb") as handle:
        data = tomllib.load(handle)
    keys = data.get("keys", {}).get("overrides", {})
    return {mode: dict(binds) for mode, binds in keys.items()}


def cmd_probe(args) -> int:
    from . import keyprobe
    if args.machine:
        print("\n".join(keyprobe.machine_lines()))
    else:
        keyprobe.probe(verbose=True)
    return 0


def cmd_doc(args) -> int:
    if args.write:
        problems = D.write()
        print("wrote %s" % D.DOC)
        for p in problems:
            print("note: %s" % p)
        return 0
    problems = D.check()
    if problems:
        for p in problems:
            print("drift: %s" % p)
        return 1
    print("ADR-006 generated blocks are current.")
    return 0


def build(parser: argparse.ArgumentParser) -> None:
    sub = parser.add_subparsers(dest="cmd", required=True)

    sub.add_parser("views").set_defaults(func=cmd_views)

    p = sub.add_parser("keys")
    p.add_argument("--cheatsheet", action="store_true")
    p.set_defaults(func=cmd_keys)

    p = sub.add_parser("layout")
    p.add_argument("view")
    p.add_argument("-c", "--cols", type=int)
    p.add_argument("-r", "--rows", type=int)
    p.set_defaults(func=cmd_layout)

    p = sub.add_parser("fit")
    p.add_argument("view")
    p.add_argument("size")
    p.set_defaults(func=cmd_fit)

    p = sub.add_parser("press")
    p.add_argument("sequence")
    p.add_argument("--view", default="queue")
    p.add_argument("--mode", default="list")
    p.set_defaults(func=cmd_press)

    sub.add_parser("tasks").set_defaults(func=cmd_tasks)
    sub.add_parser("matrix").set_defaults(func=cmd_matrix)
    sub.add_parser("palette").set_defaults(func=cmd_palette)

    p = sub.add_parser("conflicts")
    p.add_argument("--toml")
    p.add_argument("--set", action="append")
    p.set_defaults(func=cmd_conflicts)

    p = sub.add_parser("probe")
    p.add_argument("--machine", action="store_true")
    p.set_defaults(func=cmd_probe)

    p = sub.add_parser("doc")
    p.add_argument("--check", action="store_true")
    p.add_argument("--write", action="store_true")
    p.set_defaults(func=cmd_doc)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="fathom tui",
                                     description="ADR-006 as a verb surface")
    build(parser)
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
