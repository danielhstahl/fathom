#!/usr/bin/env python3
"""The Linux system packages, repackaged from the release archives (`e7.4`, **reco-3q4**).

`cargo-dist` builds tarballs, zips, installers, an msi and a Homebrew formula, and it has no deb or rpm
target — so the two package formats most Linux users reach for were the gap this ticket had to close. The
way it closes it is `[[dist.extra-artifacts]]` in `dist-workspace.toml`: `dist` runs
`packaging/linux-packages.sh` during its global phase, and every per-target archive has already been
downloaded back into `target/distrib/` by then. That ordering is the whole design:

    tar.xz (built on the per-target runner)  ->  .deb / .rpm  (repacked here, same bytes)

so a `.deb` contains *the same binary the tarball contains*, not a second compile of the tree that
happened to run on the release machine. `--from-binary` exists for a local rehearsal and says so loudly,
because a package built from whatever is in `target/debug` and named like a release is exactly the kind
of artefact that gets shipped by accident.

Layout is the two distros' own convention, not an invention:

    /usr/bin/fathom
    /usr/share/man/man1/fathom*.1.gz                (gzipped: policy in Debian, expected in Fedora)
    /usr/share/bash-completion/completions/fathom
    /usr/share/zsh/{vendor-completions|site-functions}/_fathom
    /usr/share/fish/vendor_completions.d/fathom.fish
    /usr/share/doc/fathom/{README.md,CHANGELOG.md,copyright}

The completions and man pages come out of the archive, which is why they are in it at all
(`include` in `dist-workspace.toml`, generated by `tools/gen_shell_artifacts.py`): the package manager
is then relocating files that the release already carried, and cannot invent a third copy of a flag list.

Two rules keep the naming honest, because `dpkg -i` and `dnf install` read the file name:

  * a Debian/RPM **upstream version may not contain `-`**, so `0.1.0-alpha.1` becomes `0.1.0~alpha.1`.
    `~` is the spelling both formats agree means "sorts before the release it is a prerelease of";
  * every file this writes is listed in `dist-workspace.toml`'s `extra-artifacts` list **with its
    version in the name**, and `cross_check_config` compares the two. A version bump that forgets the
    config is a failed build here (and `tools/check_release.py` R16 is the same rule offline), which is
    the loud version of a silent misnamed package.

`.rpm` needs `rpmbuild`, which is not in the runner image; `packaging/linux-packages.sh` installs it
(the Debian and Ubuntu package that carries it is called `rpm`). `.deb` is written here, byte-for-byte
reproducibly (zero mtimes, sorted members, `gzip mtime=0`) because an artefact nobody can reproduce is an
artefact nobody can verify. `--verify` reads the results back — with `dpkg-deb` and `rpm` when they are
installed, and with this file's own reader always — so "it built" is never the same claim as "it parses".

The spec's `%files` list is **generated from the relocation map**, not typed out beside it
(`spec_files`): `rpmbuild` refuses any entry that does not begin with `/`, and the map is deliberately
relative because that is what a `.deb`'s data tar needs — one relative line there is no `.rpm` at all,
which is how the release job died with `File must begin with "/"` (**reco-ndf**). `spec_problems` is that
rule checked before `rpmbuild` is asked, and `rpm -qlp` is what reads the finished package's own file
list back.
"""

