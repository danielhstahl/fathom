#!/usr/bin/env python3
"""The Linux system packages, repackaged from the release archives (`e7.4`, **reco-3q4**).

`cargo-dist` builds tarballs, zips, installers, an msi and a Homebrew formula, and it has no deb or rpm
target — so the two package formats most Linux users reach for were the gap this ticket had to close. The
way it closes it is `[[dist.extra-artifacts]]` in `dist-workspace.toml`: `dist` runs
`packaging/linux-packages.sh` during its global phase, and every per-target archive has already been
downloaded back into `target/distrib/` by then. That ordering is the whole design:

    tar.xz (built on the per-target runner)  ->  .deb / .rpm  (repacked here, same bytes)

so a `.deb` contains *the same binary the tarball contains*, not a second compile of the tree that
happened to run on the release machine. `--from-binary` exists for a local rehearsal and says so loudly,
because a package built from whatever is in `target/debug` and named like a release is exactly the kind
of artefact that gets shipped by accident.

Layout is the two distros' own convention, not an invention:

    /usr/bin/fathom
    /usr/share/man/man1/fathom*.1.gz                (gzipped: policy in Debian, expected in Fedora)
    /usr/share/bash-completion/completions/fathom
    /usr/share/zsh/{vendor-completions|site-functions}/_fathom
    /usr/share/fish/vendor_completions.d/fathom.fish
    /usr/share/doc/fathom/{README.md,CHANGELOG.md,copyright}

The completions and man pages come out of the archive, which is why they are in it at all
(`include` in `dist-workspace.toml`, generated by `tools/gen_shell_artifacts.py`): the package manager
is then relocating files that the release already carried, and cannot invent a third copy of a flag list.

Two rules keep the naming honest, because `dpkg -i` and `dnf install` read the file name:

  * a Debian/RPM **upstream version may not contain `-`**, so `0.1.0-alpha.1` becomes `0.1.0~alpha.1`.
    `~` is the spelling both formats agree means "sorts before the release it is a prerelease of";
  * every file this writes is listed in `dist-workspace.toml`'s `extra-artifacts` list **with its
    version in the name**, and `cross_check_config` compares the two. A version bump that forgets the
    config is a failed build here (and `tools/check_release.py` R16 is the same rule offline), which is
    the loud version of a silent misnamed package.

`.rpm` needs `rpmbuild`, which is not in the runner image; `packaging/linux-packages.sh` installs it.
`.deb` is written here, byte-for-byte reproducibly (zero mtimes, sorted members, `gzip mtime=0`) because
an artefact nobody can reproduce is an artefact nobody can verify. `--verify` reads the results back —
with `dpkg-deb` and `rpm` when they are installed, and with this file's own reader always — so "it built"
is never the same claim as "it parses".
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DISTRIB = ROOT / "target" / "distrib"
OUT = ROOT / "target" / "packaging"
CONFIG = ROOT / "dist-workspace.toml"
CARGO = ROOT / "Cargo.toml"

#: The Linux targets we package, and what each is called by the two package managers. Only the glibc
#: triples: the musl archive is the static build, and a `.deb` of a static binary would advertise
#: dependencies it does not have while hiding that it is a different build.
TARGETS = {
    "x86_64-unknown-linux-gnu": {"deb": "amd64", "rpm": "x86_64"},
    "aarch64-unknown-linux-gnu": {"deb": "arm64", "rpm": "aarch64"},
}

#: Where a shell looks for a completion file, per distro family. zsh is the only one that differs: Debian
#: invented `vendor-completions`, Fedora kept `site-functions`, and both are correct on their own system.
ZSH_DIR = {"deb": "usr/share/zsh/vendor-completions", "rpm": "usr/share/zsh/site-functions"}
SHELL_DIRS = {
    "deb": {
        "completions/bash/fathom": "usr/share/bash-completion/completions/fathom",
        "completions/zsh/_fathom": ZSH_DIR["deb"] + "/_fathom",
        "completions/fish/fathom.fish": "usr/share/fish/vendor_completions.d/fathom.fish",
    },
    "rpm": {
        "completions/bash/fathom": "usr/share/bash-completion/completions/fathom",
        "completions/zsh/_fathom": ZSH_DIR["rpm"] + "/_fathom",
        "completions/fish/fathom.fish": "usr/share/fish/vendor_completions.d/fathom.fish",
    },
}

DOCS = ("README.md", "CHANGELOG.md")


# ---------------------------------------------------------------------------
# the version, and the names it has to appear in
# ---------------------------------------------------------------------------


def workspace_version() -> str:
    data = tomllib.loads(CARGO.read_text())
    return str(data["workspace"]["package"]["version"])


def package_version(version: str) -> str:
    """`0.1.0-alpha.1` → `0.1.0~alpha.1`, which is what both package managers will accept.

    A `-` in an upstream version is a revision separator in Debian and illegal in RPM's, so it cannot be
    kept. `~` is the agreed "less than" marker: `0.1.0~alpha.1 < 0.1.0`, which is the ordering the
    prerelease exists to have.
    """
    return version.replace("-", "~", 1)


def metadata() -> dict:
    """The package metadata, read from the manifest that ships — never retyped here."""
    cli = tomllib.loads((ROOT / "crates" / "fathom-cli" / "Cargo.toml").read_text())["package"]
    return {
        "name": "fathom",
        "version": package_version(workspace_version()),
        "raw_version": workspace_version(),
        "summary": str(cli.get("description", "fathom")),
        "homepage": str(cli.get("homepage") or cli.get("repository") or ""),
        "license": tomllib.loads(CARGO.read_text())["workspace"]["package"]["license"],
        "maintainer": (cli.get("authors") or ["unknown"])[0],
    }


def configured_artifacts() -> list[str]:
    """The `extra-artifacts` paths `dist` will upload, so the two files can be checked against each other."""
    config = tomllib.loads(CONFIG.read_text())
    paths: list[str] = []
    for extra in config.get("dist", {}).get("extra-artifacts", []):
        paths.extend(str(p) for p in extra.get("artifacts", []))
    return paths


def cross_check_config(written: list[pathlib.Path], out: pathlib.Path, partial: bool = False) -> list[str]:
    """Every file written must be the file `dist` was told to upload, and nothing more.

    `dist` treats a missing listed path as a build failure and an unlisted file as nothing at all — so a
    drift here is either a red release or a package that silently never shipped. Naming both directions is
    the point.
    """
    want = {path.rsplit("/", 1)[-1] for path in configured_artifacts()}
    got = {path.name for path in written}
    problems = []
    for name in sorted(want - got):
        if not _is_package_name(name):
            continue  # another extra-artifact entry, not one of ours
        problems.append("dist-workspace.toml lists %s, which was not written" % name)
    for name in sorted(got - want):
        problems.append("%s was written, but dist-workspace.toml does not list it (it would never ship)"
                        % name)
    if out != OUT or partial:
        # A rehearsal directory, or a build that could not stage every target (one archive missing, or
        # `--skip-rpm`): the config describes the *complete* release set, so comparing a partial one
        # against it would only teach whoever rehearsed to ignore the checker.
        return []
    return problems


def _is_package_name(name: str) -> bool:
    return name.endswith((".deb", ".rpm", ".deb.sha256", ".rpm.sha256"))


# ---------------------------------------------------------------------------
# staging: one tree per format, in the layout that format expects
# ---------------------------------------------------------------------------


class Stage:
    """A directory-as-bytes: `{relative path: (mode, bytes)}`, sorted on write."""

    def __init__(self) -> None:
        self.files: dict[str, tuple[int, bytes]] = {}

    def add(self, rel: str, body: bytes, mode: int = 0o644) -> None:
        self.files[rel.lstrip("/")] = (mode, body)

    def names(self) -> list[str]:
        return sorted(self.files)

    def size(self) -> int:
        return sum(len(body) for _, body in self.files.values())


def _archive_root(archive: pathlib.Path) -> str:
    with tarfile.open(archive, "r:xz") as bundle:
        tops = {member.name.split("/")[0] for member in bundle.getmembers()}
    if len(tops) != 1:
        raise SystemExit("%s is not a dist archive (no single root directory: %s)" % (archive, tops))
    return tops.pop()


def stage_from_archive(archive: pathlib.Path, flavour: str) -> Stage:
    """Relocate a release archive into the package's FHS layout.

    Only the files a package manager owns are taken; the archive's own top-level directory is the price
    of `tar xJf` being pleasant on a machine with no package manager, and it disappears here.
    """
    stage = Stage()
    prefix = _archive_root(archive) + "/"
    with tarfile.open(archive, "r:xz") as bundle:
        members = {member.name[len(prefix):]: member for member in bundle.getmembers()
                   if member.isfile() and member.name.startswith(prefix)}
        binary = members.get("fathom")
        if binary is None:
            raise SystemExit("%s has no `fathom` in it" % archive)
        stage.add("usr/bin/fathom", bundle.extractfile(binary).read(), 0o755)

        missing = [rel for rel in SHELL_DIRS[flavour] if rel not in members]
        if missing:
            raise SystemExit(
                "%s has no %s — the archive is older than `include` in dist-workspace.toml, or "
                "tools/gen_shell_artifacts.py never ran" % (archive, ", ".join(missing)))
        for rel, dest in SHELL_DIRS[flavour].items():
            stage.add(dest, bundle.extractfile(members[rel]).read(), 0o644)

        pages = {name: member for name, member in members.items() if name.startswith("man/man1/")
                 and name.endswith(".1")}
        if not pages:
            raise SystemExit("%s has no man pages in it" % archive)
        for name, member in sorted(pages.items()):
            stage.add("usr/share/" + name + ".gz", gzip.compress(bundle.extractfile(member).read(),
                                                                 mtime=0), 0o644)
        for doc in DOCS:
            if doc in members:
                stage.add("usr/share/doc/fathom/" + doc, bundle.extractfile(members[doc]).read(), 0o644)
    return stage


def stage_from_binary(binary: pathlib.Path, flavour: str) -> Stage:
    """A rehearsal stage, from a built binary and the committed shell artefacts. Never the release path."""
    stage = Stage()
    stage.add("usr/bin/fathom", binary.read_bytes(), 0o755)
    source = ROOT / "packaging"
    for rel, dest in SHELL_DIRS[flavour].items():
        stage.add(dest, (source / rel).read_bytes(), 0o644)
    for page in sorted((source / "man/man1").glob("*.1")):
        stage.add("usr/share/man/man1/" + page.name + ".gz", gzip.compress(page.read_bytes(), mtime=0),
                  0o644)
    for doc in DOCS:
        if (ROOT / doc).exists():
            stage.add("usr/share/doc/fathom/" + doc, (ROOT / doc).read_bytes(), 0o644)
    return stage


def add_copyright(stage: Stage, meta: dict) -> None:
    """`/usr/share/doc/fathom/copyright`, because Debian asks for one and honesty is cheap.

    It states the licence the manifest declares and says where the text is *not* yet, rather than
    inventing a licence file the repository does not carry.
    """
    text = (
        "Name: fathom\n"
        "Comment: this package is built from the fathom release archive\n"
        "Homepage: %s\n"
        "License: %s\n"
        "Copyright: (c) %s\n"
        "\n"
        "The licence texts are not vendored in the source tree yet (the workspace declares\n"
        "`license = \"%s\"` and nothing more). Until they are, this is the licence statement this\n"
        "package makes, and `fathom --version` names the version it was built from.\n"
        % (meta["homepage"], meta["license"], meta["maintainer"], meta["license"])
    )
    stage.add("usr/share/doc/fathom/copyright", text.encode(), 0o644)


# ---------------------------------------------------------------------------
# .deb: an `ar` of three members, written by hand so it is reproducible
# ---------------------------------------------------------------------------


def ar_member(name: str, body: bytes) -> bytes:
    """One `ar` member: the 60-byte header dpkg reads, then the body, then a pad byte when odd."""
    header = "%-16s%-12d%-6d%-6d%-8o%-10d`\n" % (name, 0, 0, 0, 0o100644, len(body))
    assert len(header) == 60, "ar headers are 60 bytes: %r" % header
    return header.encode() + body + (b"\n" if len(body) % 2 else b"")


def tar_bytes(members: list[tuple[str, int, bytes]]) -> bytes:
    """A deterministic tar: uid/gid 0, root/root, zero mtimes, and the order handed in."""
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w", format=tarfile.GNU_FORMAT) as bundle:
        for name, mode, body in members:
            info = tarfile.TarInfo(name="./" + name)
            info.size = len(body)
            info.mode = mode
            info.mtime = 0
            info.type = tarfile.REGTYPE
            info.uid = 0
            info.gid = 0
            info.uname = "root"
            info.gname = "root"
            bundle.addfile(info, io.BytesIO(body))
    return buffer.getvalue()


def control_file(meta: dict, arch: str, stage: Stage) -> bytes:
    description = meta["summary"].strip() or "fathom"
    lines = ["%s: %s" % (field, value) for field, value in [
        ("Package", meta["name"]),
        ("Version", meta["version"]),
        ("Architecture", arch),
        ("Maintainer", meta["maintainer"]),
        ("Priority", "optional"),
        ("Section", "utils"),
        ("Homepage", meta["homepage"]),
        ("Installed-Size", str(max(1, stage.size() // 1024))),
    ]]
    lines.append("Description: %s" % description.splitlines()[0])
    for extra in description.splitlines()[1:] or ["Architecture-aware review of an agent-written repository."]:
        lines.append(" " + extra)
    return ("\n".join(lines) + "\n").encode()


def build_deb(stage: Stage, out: pathlib.Path, meta: dict, arch: str) -> pathlib.Path:
    members = [(name, stage.files[name][0], stage.files[name][1]) for name in stage.names()]
    md5s = "\n".join("%s  %s" % (hashlib.md5(body).hexdigest(), name) for name, _, body in members)
    control = tar_bytes([("control", 0o644, control_file(meta, arch, stage)),
                         ("md5sums", 0o644, (md5s + "\n").encode())])
    data = tar_bytes(members)
    payload = (b"!<arch>\n"
               + ar_member("debian-binary", b"2.0\n")
               + ar_member("control.tar.gz", gzip.compress(control, mtime=0))
               + ar_member("data.tar.gz", gzip.compress(data, mtime=0)))
    path = out / ("%s_%s_%s.deb" % (meta["name"], meta["version"], arch))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(payload)
    return path


def read_deb(path: pathlib.Path) -> dict:
    """Read a `.deb` back: the ar members, the control fields, and the file list.

    Deliberately independent of `dpkg-deb`, which is not installed everywhere a release is checked. It
    proves the container parses and the layout is what was staged; it does not prove `dpkg` is happy,
    which is what `--verify` uses the real tool for when it is present.
    """
    blob = path.read_bytes()
    if not blob.startswith(b"!<arch>\n"):
        raise SystemExit("%s is not an ar archive" % path)
    out: dict[str, bytes] = {}
    offset = len(b"!<arch>\n")
    while offset < len(blob):
        header = blob[offset:offset + 60]
        if len(header) < 60:
            break
        fields = header.decode("ascii")
        name = fields[0:16].strip().rstrip("/")
        size = int(fields[48:58].strip())
        body = blob[offset + 60:offset + 60 + size]
        out[name] = body
        offset += 60 + size + (size % 2)
    control = dict(_control_fields(_tar_file(gzip.decompress(out["control.tar.gz"]), "control")))
    files = []
    with tarfile.open(fileobj=io.BytesIO(gzip.decompress(out["data.tar.gz"]))) as bundle:
        for member in bundle.getmembers():
            files.append((member.name[2:] if member.name.startswith("./") else member.name,
                          member.mode, member.size, member.uid, member.gid))
    return {"ar": sorted(out), "control": control, "files": sorted(files),
            "md5sums": sorted(line.split()[1] for line in
                              _tar_file(gzip.decompress(out["control.tar.gz"]), "md5sums").splitlines()
                              if line.strip())}


def _tar_file(blob: bytes, name: str) -> bytes:
    with tarfile.open(fileobj=io.BytesIO(blob)) as bundle:
        for member in bundle.getmembers():
            if member.name.lstrip("./") == name:
                handle = bundle.extractfile(member)
                return handle.read() if handle else b""
    return b""


def _control_fields(control: bytes):
    for line in control.decode().splitlines():
        if ":" in line and not line.startswith(" "):
            key, _, value = line.partition(":")
            yield key.strip(), value.strip()


# ---------------------------------------------------------------------------
# .rpm: rpmbuild, because that is the reference implementation
# ---------------------------------------------------------------------------


SPEC = """\
Name:           {name}
Version:        {version}
Release:        1
Summary:        {summary}
License:        {license}
URL:            {homepage}
BuildArch:      {arch}
%define stage   {stage}

%description
{summary}

%prep
# nothing to unpack: the staged tree is already an installed filesystem

%install
rm -rf "$RPM_BUILD_ROOT"
mkdir -p "$RPM_BUILD_ROOT"
cp -a "{stage}/." "$RPM_BUILD_ROOT/"

%files
%defattr(-,root,root,-)
%attr(0755,root,root) /usr/bin/{name}
/usr/share/bash-completion/completions/{name}
{zsh}
/usr/share/fish/vendor_completions.d/{name}.fish
/usr/share/doc/{name}
%dir /usr/share/man/man1
/usr/share/man/man1/*.1.gz

%changelog
"""


def build_rpm(stage: Stage, out: pathlib.Path, meta: dict, arch: str) -> pathlib.Path:
    """Build an `.rpm` with `rpmbuild`, from the same staged tree as the `.deb`.

    Using the reference implementation rather than writing an RPM by hand is a deliberate trade: the
    output carries a build time and a build host, so it is not reproducible the way the `.deb` here is,
    and in exchange it is guaranteed to be an RPM. `packaging/linux-packages.sh` installs the tool; if
    it is missing this fails rather than skipping, because a release that quietly shipped no `.rpm` is
    worse than a red release nobody can miss.
    """
    if shutil.which("rpmbuild") is None:
        raise SystemExit(
            "rpmbuild is not installed, so no .rpm can be written. On a Debian/Ubuntu box: "
            "`sudo apt-get install -y --no-install-recommends rpmbuild`. `--skip-rpm` is the rehearsal "
            "escape hatch; a release build never passes it.")
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="fathom-rpm-") as work:
        top = pathlib.Path(work)
        stage_dir = top / "stage"
        _write_stage(stage, stage_dir)
        spec = top / "fathom.spec"
        spec.write_text(SPEC.format(name=meta["name"], version=meta["version"],
                                    summary=meta["summary"].splitlines()[0], license=meta["license"],
                                    homepage=meta["homepage"], arch=arch, stage=str(stage_dir),
                                    zsh=ZSH_DIR["rpm"] + "/_" + meta["name"]))
        rpmdir = top / "rpms"
        command = ["rpmbuild", "-bb", "--nodeps", "--noclean", "--target", arch,
                   "--define", "_topdir %s" % top, "--define", " _tmppath %s/tmp" % top,
                   "--define", "_rpmdir %s" % rpmdir, str(spec)]
        result = subprocess.run(command, capture_output=True, text=True, check=False)
        built = sorted(rpmdir.glob("**/*.rpm")) if rpmdir.exists() else []
        if result.returncode != 0 or not built:
            raise SystemExit("rpmbuild failed (exit %d):\n%s\n%s"
                             % (result.returncode, result.stdout, result.stderr))
        target = out / ("%s-%s-1.%s.rpm" % (meta["name"], meta["version"], arch))
        shutil.copyfile(built[0], target)
        return target


def _write_stage(stage: Stage, where: pathlib.Path) -> None:
    for name, (mode, body) in stage.files.items():
        path = where / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(body)
        path.chmod(mode)


# ---------------------------------------------------------------------------
# checksums and verification
# ---------------------------------------------------------------------------


def write_sha256(path: pathlib.Path) -> pathlib.Path:
    """One `.sha256` beside one artefact, in `dist`'s own format: `<digest>  <name>`.

    `dist` checksums the artefacts it builds (`sha256.sum` and one `.sha256` per archive); extra
    artefacts are ours, so the convention has to be kept here or the packages are the only files on the
    release page with nothing to check them against.
    """
    side = path.with_name(path.name + ".sha256")
    side.write_text("%s  %s\n" % (hashlib.sha256(path.read_bytes()).hexdigest(), path.name))
    return side


def verify(path: pathlib.Path) -> list[str]:
    """Read the artefact back with whatever tool the machine has; never trust that it wrote."""
    problems: list[str] = []
    if path.suffix == ".deb":
        read = read_deb(path)
        if read["ar"] != ["control.tar.gz", "data.tar.gz", "debian-binary"]:
            problems.append("%s: unexpected ar members %s" % (path.name, read["ar"]))
        names = [name for name, _, _, _, _ in read["files"]]
        for required in ("usr/bin/fathom", "usr/share/doc/fathom/copyright"):
            if required not in names:
                problems.append("%s: %s is not in the data archive" % (path.name, required))
        if not any(name.startswith("usr/share/man/man1/") for name in names):
            problems.append("%s: no man pages" % path.name)
        if read["control"].get("Package") != "fathom":
            problems.append("%s: control's Package is %r" % (path.name, read["control"].get("Package")))
        if not read["md5sums"]:
            problems.append("%s: no md5sums, so dpkg cannot verify its own install" % path.name)
        if shutil.which("dpkg-deb"):
            problems.extend(_run_tool(["dpkg-deb", "--info", str(path)], path, "dpkg-deb --info"))
            problems.extend(_run_tool(["dpkg-deb", "--contents", str(path)], path, "dpkg-deb --contents"))
        else:
            print("  note  dpkg-deb not installed: checked the container, not dpkg's opinion of it")
    else:
        if shutil.which("rpm"):
            problems.extend(_run_tool(["rpm", "-qp", "--nosignature", str(path)], path, "rpm -qp"))
        else:
            print("  note  rpm not installed: the .rpm was written by rpmbuild and not read back")
    return problems


def _run_tool(command: list[str], path: pathlib.Path, label: str) -> list[str]:
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        return ["%s: `%s` says: %s" % (path.name, label, (result.stdout + result.stderr).strip())]
    return []


