/// Render the artefact as one HTML document.
#[must_use]
pub fn render(record: &Record) -> String {
    let mut out = String::new();
    out.push_str("<!DOCTYPE html>\n");
    out.push_str("<html lang=\"en\">\n<head>\n");
    out.push_str("<meta charset=\"utf-8\">\n");
    out.push_str(&format!(
        "<meta http-equiv=\"Content-Security-Policy\" content=\"{CSP}\">\n"
    ));
    out.push_str("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
    out.push_str(&format!(
        "<meta name=\"generator\" content=\"{} {}\"><title>Fathom review record — {}</title>\n",
        escape(&record.generator),
        record.schema_version,
        escape(&record.scope.asked)
    ));
    out.push_str("<style>");
    out.push_str(STYLE.trim());
    out.push_str("</style>\n</head>\n<body>\n");

    header(&mut out, record);
    toc(&mut out);
    summary_card(&mut out, record);
    section_states(&mut out, record);
    episodes(&mut out, record);
    dependencies(&mut out, record);
    architecture(&mut out, record);
    findings(&mut out, record);
    checklist(&mut out, record);
    signoffs(&mut out, record);
    memory(&mut out, record);
    commits(&mut out, record);
    gaps(&mut out, record);
    footer(&mut out, record);

    out.push_str("</body>\n</html>\n");
    out
}

