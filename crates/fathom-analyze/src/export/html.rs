//! `export::html` — the audit rendering: one self-contained, printable, inert page (`e5.7`).
//!
//! # What "self-contained" costs, and buys
//!
//! One file, no stylesheet, no font, no script, no image: the artefact is mailed, attached to a ticket,
//! opened from a USB stick and printed for an auditor who will not be asked for a second file. That is
//! also what makes it safe — an offline document has nothing to fetch — and the content policy at [`CSP`]
//! says so out loud to the browser as well as to the reader.
//!
//! # Safety, in the order the defences apply
//!
//! 1. **Nothing from outside this module reaches the markup unescaped.** Every string that came from a
//!    commit message, a path, a review note, a detector sentence or a delta document goes through
//!    [`escape`], so no input can close a tag or open an attribute. The test feeds the renderer a commit
//!    message built out of tags, quotes and `javascript:` and asserts none of it survives as markup.
//! 2. **Links are built, never interpolated.** The only `href`s in the document are this artefact's own
//!    anchors (generated by [`super::markdown::slug`] from ids this crate controls) and commit URLs
//!    (`the repository's remote` + a hex object id). Text can never *become* an `href`; [`href`] is the
//!    gate, and it drops a URL that carries credentials, whitespace or a scheme it did not ask for.
//! 3. **The page declares itself scriptless.** [`CSP`] is shipped in a `meta` element and there is no
//!    `<script>` in the template to begin with — the third defence is not load-bearing, which is the point.
//!
//! # Printing
//!
//! `@page` margins, page-break rules that keep an episode's block whole, hidden navigation, and links
//! printed as their own targets where the target is a URL. A printed page cannot carry a hyperlink, so the
//! commit table prints the URL beside the link rather than under it.

