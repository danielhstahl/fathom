fn header(out: &mut String, record: &Record) {
    out.push_str(&format!(
        "<h1>Fathom review record — <code>{}</code></h1>\n",
        escape(&record.scope.asked)
    ));
    let range = match (record.scope.from.as_deref(), record.scope.to.as_deref()) {
        (Some(from), Some(to)) if from == to => {
            format!("resolved to <code>{}</code>", escape(from))
        }
        (Some(from), Some(to)) => format!(
            "resolved from <code>{}</code> to <code>{}</code>",
            escape(from),
            escape(to)
        ),
        _ => "<span class=\"bad\">did not resolve to commits this repository has</span>".to_owned(),
    };
    out.push_str("<ul class=\"kv\">");
    li(
        out,
        &format!(
            "<strong>Scope</strong> — <code>{}</code> · {} · <span class=\"muted\">{}</span>",
            escape(&record.scope.asked),
            range,
            escape(&record.scope.episode_order)
        ),
    );
    li(
        out,
        &format!(
            "<strong>Verdict</strong> — {}",
            escape(&record.summary.verdict)
        ),
    );
    li(
        out,
        &format!(
            "<strong>Scale</strong> — {} episode(s) · {} commit(s) · {} file(s) · +{} −{} · reviewable churn {}",
            record.summary.episodes,
            record.scope.commits,
            record.summary.files,
            record.summary.add,
            record.summary.del,
            record.summary.reviewable_churn
        ),
    );
    li(
        out,
        &format!(
            "<strong>Built from</strong> — {} · written by <code>{}</code> (<code>{}</code>)",
            record
                .provenance
                .contracts
                .iter()
                .map(|(who, what)| format!("{who} <code>{}</code>", escape(what)))
                .collect::<Vec<_>>()
                .join(" · "),
            escape(&record.generator),
            escape(&record.provenance.produced_by)
        ),
    );
    out.push_str("</ul>\n");
}

fn toc(out: &mut String) {
    const ENTRIES: [(&str, &str); 10] = [
        ("summary", "Summary card"),
        ("answers", "What this record can and cannot answer"),
        ("episodes", "Episodes"),
        ("dependencies", "Dependency delta"),
        ("architecture", "Architecture delta"),
        ("findings", "Findings with evidence"),
        ("checklist", "Operator-action checklist"),
        ("signoffs", "Sign-offs"),
        ("commits", "Commits"),
        ("gaps", "What this record cannot answer"),
    ];
    out.push_str("<nav class=\"toc no-print\"><strong>Contents</strong><ol>");
    for (anchor, label) in ENTRIES {
        out.push_str(&format!(
            "<li><a href=\"#{anchor}\">{}</a></li>",
            escape(label)
        ));
    }
    out.push_str("</ol></nav>\n");
}

fn summary_card(out: &mut String, record: &Record) {
    out.push_str("<section id=\"summary\"><h2>Summary card</h2>\n");
    if let Some(top) = &record.summary.top_risk {
        out.push_str(&format!(
            "<p>Highest risk in scope: <code>{}</code></p>\n",
            escape(top)
        ));
    }
    if record.episodes.is_empty() {
        out.push_str("<p><em>Nothing in this range reached the index.</em></p>\n");
    } else {
        out.push_str(
            "<table><thead><tr><th>episode</th><th>subject</th><th>risk</th>\
                      <th class=\"num\">commits</th><th class=\"num\">lines</th>\
                      <th class=\"num\">files</th><th class=\"num\">reviewable</th>\
                      <th>decision</th><th>signed by</th></tr></thead><tbody>",
        );
        for episode in &record.episodes {
            let reference = &episode.delta.episode;
            out.push_str(&format!(
                "<tr><td><a href=\"#{}\"><code>{}</code></a></td><td>{}</td>\
                 <td><code>{}</code></td><td class=\"num\">{}</td>\
                 <td class=\"num\">+{} −{}</td><td class=\"num\">{}</td>\
                 <td class=\"num\">{}</td><td><code>{}</code></td><td>{}</td></tr>",
                super::markdown::episode_anchor(&reference.id),
                escape(&reference.id),
                escape(&reference.summary),
                escape(&episode.risk_line()),
                reference.n_commits,
                episode.delta.totals.n_add,
                episode.delta.totals.n_del,
                episode.delta.totals.n_files,
                episode.delta.totals.reviewable_churn,
                escape(&episode.decision),
                episode.accepted_by.as_ref().map_or_else(
                    || "—".to_owned(),
                    |entry| format!("<code>{}</code>", escape(entry)),
                )
            ));
        }
        out.push_str("</tbody></table>\n");
    }
    out.push_str("</section>\n");
}

fn section_states(out: &mut String, record: &Record) {
    out.push_str("<section id=\"answers\"><h2>What this record can and cannot answer</h2>\n");
    out.push_str("<table><thead><tr><th>section</th><th>question</th><th class=\"num\">measured</th>\
                  <th class=\"num\">partial</th><th class=\"num\">unavailable</th><th>owner</th></tr></thead><tbody>");
    for state in &record.scope.section_states {
        out.push_str(&format!(
            "<tr><td><code>{}</code></td><td>{}</td><td class=\"num\">{}</td><td class=\"num\">{}</td>\
             <td class=\"num\">{}</td><td><code>{}</code></td></tr>",
            escape(&state.id),
            escape(&state.question),
            state.measured,
            state.partial,
            state.unavailable,
            escape(&state.owner)
        ));
    }
    out.push_str("</tbody></table></section>\n");
}

fn episodes(out: &mut String, record: &Record) {
    out.push_str("<section id=\"episodes\"><h2>Episodes</h2>\n");
    if record.episodes.is_empty() {
        out.push_str("<p><em>None. The range resolved to no episode the index knows.</em></p>\n");
    }
    for episode in &record.episodes {
        episode_block(out, episode);
    }
    out.push_str("</section>\n");
}

/// One episode: the composer's narrative as a claim list with its citations, then the rows behind it.
fn episode_block(out: &mut String, episode: &EpisodeView) {
    let reference = &episode.delta.episode;
    let anchor = super::markdown::episode_anchor(&reference.id);
    out.push_str(&format!(
        "<section class=\"episode\" id=\"{anchor}\"><h3><a href=\"#{anchor}-files\"><code>{}</code></a> — {}</h3>\n",
        escape(&reference.id),
        escape(&reference.summary)
    ));

    // The narrative: the same claims and citations `fathom narrative` composes, laid out rather than
    // re-worded. The composition is a pure function of the delta document this record already carries, so
    // there is one prose and two layouts — which is the whole point of `e4.7`'s last criterion.
    {
        let narrative =
            crate::narrative::compose(&episode.delta, &crate::narrative::Options::new());
        if narrative.to_markdown() != episode.narrative_markdown {
            out.push_str(
                "<p class=\"bad\">the narrative in this record is not the bytes the composer \
                 produces for this episode</p>\n",
            );
        }
        out.push_str("<h4>");
        out.push_str(&escape(&narrative.title));
        out.push_str("</h4><ul class=\"claims\">");
        let mut section: Option<String> = None;
        for claim in &narrative.claims {
            if section.as_deref() != Some(claim.section.as_str()) {
                section = Some(claim.section.clone());
                out.push_str(&format!(
                    "</ul><h4>{}</h4><ul class=\"claims\">",
                    escape(&title_of(&claim.section))
                ));
            }
            out.push_str("<li>");
            out.push_str(&escape(&claim.text));
            for id in &claim.cites {
                out.push_str(&format!(
                    " <sup><a href=\"#{}-cite-{id}\">[{}]</a></sup>",
                    anchor,
                    escape(id)
                ));
            }
            out.push('.');
        }
        out.push_str("</ul>");
        out.push_str("<h4>Evidence</h4><ul>");
        for citation in &narrative.citations {
            out.push_str(&format!(
                "<li id=\"{anchor}-cite-{}\"><code>{}</code> {} — {} — {}</li>",
                escape(&citation.id),
                escape(&citation.id),
                escape(&citation.what),
                escape(&citation.address_text()),
                escape(&citation.text)
            ));
        }
        out.push_str("</ul>");
        out.push_str(&format!(
            "<p class=\"muted\">{}</p>",
            escape(&narrative.integrity_line())
        ));
    }

    out.push_str(&format!(
        "<ul class=\"kv\"><li><strong>Decision</strong> — <code>{}</code>{}</li>\
         <li><strong>Author</strong> — {} <span class=\"muted\">({} · identity {})</span></li>\
         <li><strong>Commits</strong> — {}</li></ul>",
        escape(&episode.decision),
        episode
            .accepted_by
            .as_ref()
            .map_or_else(String::new, |entry| {
                format!(
                    " <span class=\"muted\">closed by <code>{}</code></span>",
                    escape(entry)
                )
            }),
        escape(&format!(
            "{} {}",
            reference.author_kind, reference.author_name
        )),
        escape(
            &reference
                .author_confidence
                .map_or_else(|| "?".to_owned(), |value| format!("{value:.2}")),
        ),
        escape(&crate::ledger::entry::iso_utc(reference.first_utc)),
        episode.commits.len()
    ));
    out.push_str("</ul>\n");

    if !episode.commits.is_empty() {
        out.push_str("<ul>");
        for commit in episode.commits.iter().take(LIST_CAP) {
            out.push_str(&format!(
                "<li>{} <code>{}</code> <span class=\"muted\">{} · {}</span></li>",
                commit_link(commit),
                escape(&commit.subject),
                escape(&format!("{} <{}>", commit.author, commit.email)),
                escape(&commit.stamp())
            ));
        }
        out.push_str("</ul>\n");
    }

    out.push_str(&format!(
        "<h4 id=\"{anchor}-files\">Card and file rows ({} row(s))</h4>",
        episode.delta.files.len()
    ));
    out.push_str("<table><thead><tr><th>section</th><th>state</th><th>value</th><th>owner</th></tr></thead><tbody>");
    for row in &episode.card {
        out.push_str(&format!(
            "<tr><td><code>{}</code></td><td><code>{}</code></td><td>{}</td><td><code>{}</code></td></tr>",
            escape(&row.label()),
            escape(&row.state),
            escape(&row.value),
            escape(&row.owner)
        ));
    }
    out.push_str("</tbody></table>\n");

    if !episode.delta.files.is_empty() {
        out.push_str(
            "<table><thead><tr><th class=\"num\">#</th><th>path</th><th>change</th>\
                      <th class=\"num\">+</th><th class=\"num\">−</th><th>class</th><th>noise</th>\
                      <th>surface</th></tr></thead><tbody>",
        );
        for (index, file) in episode.delta.files.iter().enumerate().take(LIST_CAP) {
            out.push_str(&format!(
                "<tr id=\"{anchor}-file-{index}\"><td class=\"num\">{index}</td><td><code>{}</code></td>\
                 <td><code>{}</code></td><td class=\"num\">{}</td><td class=\"num\">{}</td>\
                 <td><code>{}</code></td><td><code>{}</code></td><td><code>{}</code></td></tr>",
                escape(
                    &file
                        .old_path
                        .as_ref()
                        .map_or_else(|| file.path.clone(), |old| format!("{old} → {}", file.path))
                ),
                escape(&file.change),
                file.add,
                file.del,
                escape(&file.path_class),
                escape(&file.noise_class),
                escape(&file.surface),
            ));
        }
        out.push_str("</tbody></table>\n");
    }

    for section in &episode.delta.sections {
        out.push_str(&format!(
            "<h4><code>{}</code> — <span class=\"muted\">{}</span> — {}</h4>",
            escape(&section.id),
            escape(&section.state),
            escape(&section.question)
        ));
        if !section.figures.is_empty() {
            out.push_str("<ul>");
            for figure in section.figures.iter().take(LIST_CAP) {
                out.push_str("<li>");
                out.push_str(escape(&figure.label).as_str());
                let value = if figure.known {
                    format!(" — <code>{}</code>", escape(&figure.value))
                } else {
                    format!(
                        " — <em>unknown</em>: {}",
                        escape(figure.reason.as_deref().unwrap_or("no reason given"))
                    )
                };
                out.push_str(&value);
                out.push_str(&format!(
                    " <span class=\"evidence\">{}</span>",
                    evidence_of(episode, &figure.evidence)
                ));
                out.push_str("</li>");
            }
            out.push_str("</ul>\n");
        }
        if let Some(gap) = &section.gap {
            out.push_str(&format!(
                "<p class=\"warn\">gap — {} <span class=\"muted\">(owner <code>{}</code>{})</span></p>",
                escape(&gap.reason),
                escape(&gap.owner),
                gap.remedy
                    .as_ref()
                    .map_or_else(String::new, |remedy| format!(" · remedy <code>{}</code>", escape(remedy)))
            ));
        }
    }
    out.push_str("</section>\n");
}

fn dependencies(out: &mut String, record: &Record) {
    out.push_str("<section id=\"dependencies\"><h2>Dependency delta</h2>\n");
    let Some(deps) = &record.dependencies else {
        out.push_str(
            "<p><em>Not computed for this range.</em> The per-episode <code>dependencies</code> \
                      section above carries the reason and the ticket that owns it.</p>\n",
        );
        out.push_str("</section>\n");
        return;
    };
    out.push_str(&format!(
        "<p><strong>{}</strong> — <code>{}</code> · between <code>{}</code> · {} file(s) folded in · \
         owner <code>{}</code></p>\n",
        escape(&deps.headline),
        escape(&deps.basis),
        escape(&deps.between),
        deps.files,
        escape(&deps.owner)
    ));
    if !deps.complete {
        out.push_str(
            "<p class=\"warn\">One side of the comparison was not read completely; treat the \
                      counts as a floor.</p>\n",
        );
    }
    if !deps.counts.is_empty() {
        out.push_str("<ul class=\"kv\">");
        for (key, value) in &deps.counts {
            li(out, &format!("{key} — <code>{value}</code>"));
        }
        out.push_str("</ul>\n");
    }
    string_list(out, "Changes", &deps.changes, deps.change_remainder);
    string_list(out, "New sources", &deps.new_sources, 0);
    string_list(out, "Sources gone", &deps.sources_gone, 0);
    string_list(out, "Peer conflicts", &deps.peer_conflicts, 0);
    string_list(out, "Licences added", &deps.licenses_added, 0);
    string_list(out, "Licences removed", &deps.licenses_removed, 0);
    string_list(out, "Notes", &deps.notes, 0);
    out.push_str("</section>\n");
}

fn architecture(out: &mut String, record: &Record) {
    let arch = &record.architecture;
    out.push_str("<section id=\"architecture\"><h2>Architecture delta</h2>\n");
    out.push_str(&format!(
        "<p>Roll-up of the file rows the delta documents carry · owner <code>{}</code> · {}{}</p>\n",
        escape(&arch.owner),
        escape(&arch.basis),
        if arch.truncated {
            " · <span class=\"warn\">a file read was capped, so these rows are a floor</span>"
        } else {
            ""
        }
    ));
    if !arch.directories.is_empty() {
        out.push_str("<table><thead><tr><th>directory</th><th class=\"num\">files</th>\
                      <th class=\"num\">+</th><th class=\"num\">−</th><th>largest row</th></tr></thead><tbody>");
        for row in arch.directories.iter().take(LIST_CAP) {
            out.push_str(&format!(
                "<tr><td><code>{}</code></td><td class=\"num\">{}</td><td class=\"num\">{}</td>\
                 <td class=\"num\">{}</td><td><code>{}</code></td></tr>",
                escape(&row.path),
                row.files,
                row.add,
                row.del,
                escape(&row.largest)
            ));
        }
        out.push_str("</tbody></table>\n");
        remainder(
            out,
            arch.directories.len().saturating_sub(LIST_CAP),
            "directories",
        );
    }
    string_list(
        out,
        "Moves",
        &arch
            .renames
            .iter()
            .map(|row| format!("{} → {} ({})", row.from, row.to, row.episode))
            .collect::<Vec<_>>(),
        0,
    );
    string_list(out, "Deleted", &arch.deleted, 0);
    string_list(out, "Binary", &arch.binary, 0);
    if arch.noise_rows > 0 {
        out.push_str(&format!(
            "<p>Path-classed as generated, vendored or lockfile noise: <code>{}</code> row(s)</p>\n",
            arch.noise_rows
        ));
    }
    if !arch.surfaces.is_empty() {
        out.push_str(&format!(
            "<p>Surfaces touched: {}</p>\n",
            arch.surfaces
                .iter()
                .map(|surface| format!("<code>{}</code>", escape(surface)))
                .collect::<Vec<_>>()
                .join(" · ")
        ));
    }
    string_list(out, "What the ranking cannot see", &arch.blind_spots, 0);
    out.push_str("</section>\n");
}

