/// Escape a string for HTML text or a quoted attribute.
///
/// The five characters that can end a text node, open a tag or break out of an attribute. Everything else
/// is passed through, including unicode: an artefact that mangles a non-ASCII commit message is a worse
/// artefact, not a safer one, and none of those bytes can start a tag.
#[must_use]
pub fn escape(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 16);
    for ch in text.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&#39;"),
            c if (c as u32) < 0x20 => out.push(' '),
            c => out.push(c),
        }
    }
    out
}

/// A URL, if it is one this document is willing to link to. `None` drops the link and keeps the text.
#[must_use]
pub fn href(url: &str) -> Option<String> {
    let ok = (url.starts_with("https://") || url.starts_with("http://"))
        && !url
            .chars()
            .any(|c| c.is_whitespace() || matches!(c, '"' | '\'' | '<' | '>' | '`'))
        && url
            .split('/')
            .nth(2)
            .is_some_and(|host| !host.is_empty() && !host.contains('@'));
    ok.then(|| url.to_owned())
}

fn li(out: &mut String, html: &str) {
    out.push_str(&format!("<li>{html}</li>"));
}

fn severity_class(severity: &str) -> &'static str {
    match severity {
        "high" => "bad",
        "medium" => "warn",
        _ => "muted",
    }
}

fn reason_text(row: &super::record::SignOffRow) -> String {
    if row.reason_code.is_empty() && row.reason_label.is_empty() {
        return "—".to_owned();
    }
    if row.reason_code == row.reason_label || row.reason_label.is_empty() {
        return row.reason_code.clone();
    }
    format!("{} — {}", row.reason_code, row.reason_label)
}

fn commit_link(commit: &super::record::CommitRef) -> String {
    commit.url.as_ref().map_or_else(
        || format!("<code>{}</code>", escape(&commit.short)),
        |url| match href(url) {
            Some(url) => format!(
                "<a href=\"{url}\"><code>{}</code></a>",
                escape(&commit.short)
            ),
            None => format!("<code>{}</code>", escape(&commit.short)),
        },
    )
}

fn evidence_of(episode: &EpisodeView, evidence: &crate::insight::Evidence) -> String {
    let mut parts = Vec::new();
    if let Some(pointer) = &evidence.pointer {
        let target = pointer
            .strip_prefix("#/files/")
            .and_then(|tail| tail.parse::<usize>().ok());
        let base = super::markdown::episode_anchor(&episode.delta.episode.id);
        let anchor = match target {
            Some(index) if index < episode.delta.files.len() => {
                Some(format!("{base}-file-{index}"))
            }
            // The roll-up pointers resolve to the same heading the card and file rows sit under: one
            // heading, two names for it, because the model points at totals and files from different figures.
            _ if pointer == "#/files" || pointer.starts_with("#/totals") => {
                Some(format!("{base}-files"))
            }
            _ => None,
        };
        parts.push(match anchor {
            Some(anchor) => format!("<a href=\"#{anchor}\"><code>{}</code></a>", escape(pointer)),
            None => format!("<code>{}</code>", escape(pointer)),
        });
    }
    if let Some(run) = &evidence.run {
        parts.push(format!("run <code>{}</code>", escape(run)));
    }
    if let Some(owner) = &evidence.owner {
        parts.push(format!("owned by <code>{}</code>", escape(owner)));
    }
    parts.join(" · ")
}

fn string_list(out: &mut String, label: &str, items: &[String], remainder_count: usize) {
    if items.is_empty() {
        return;
    }
    out.push_str(&format!("<h4>{}</h4><ul>", escape(label)));
    for item in items.iter().take(LIST_CAP) {
        out.push_str(&format!("<li><code>{}</code></li>", escape(item)));
    }
    out.push_str("</ul>");
    remainder(
        out,
        items.len().saturating_sub(LIST_CAP).max(remainder_count),
        label,
    );
}

fn remainder(out: &mut String, more: usize, noun: &str) {
    if more > 0 {
        out.push_str(&format!(
            "<p class=\"muted\">… and {more} more {noun}, in the JSON artefact.</p>\n"
        ));
    }
}
