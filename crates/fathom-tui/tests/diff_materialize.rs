//! `e1.8`'s four acceptance criteria, each one a number rather than an adjective.
//!
//! 1. **Opening an episode that touched 5 000 files paints in under 300 ms.** Timed against the frame
//!    the reviewer actually gets, in the debug profile the test suite runs in, with the work that
//!    used to dominate it (a whole-tree rebuild per pane, a whole-hunk decode per window) measured
//!    separately so a regression names itself.
//! 2. **The decode cache is bounded**, and the test is the workload that would exceed the cap:
//!    enough hunks, big enough, that an unbounded cache would have to be ten times the size.
//! 3. **Rapid scrolling cannot queue unbounded work.** A thousand requests in a row, the in-flight
//!    cap asserted after every one, and the queue's own peak counter checked.
//! 4. **Rapid `]`/`]`/`]` shows progressively correct content and never stale content.** Every frame
//!    is checked for two things: that it contains nothing that belongs to another window or another
//!    shape, and that once its own hunks have arrived it is byte-identical to the frame the inline
//!    decoder would have drawn.
//!
//! The tests share the fixture corpus with the diff suite (`tests/corpus/mod.rs`) and the queue's own
//! unit tests live in `tests/materialize.rs`.
// The numbers these tests assert are measurements, and the measurement is what a reader has to see to
// believe the assertion — so the prints stay, and `cargo clippy --all-targets` stays quiet about them.
#![allow(clippy::unwrap_used, clippy::expect_used)]
#![allow(clippy::print_stdout)]

use std::sync::Arc;
use std::time::Instant;

use fathom_tui::diff::{Budget, BytesSource, DiffView, Layout, Request, Shape};
use fathom_tui::event::Bus;
use fathom_tui::materialize::Priority;

#[path = "corpus/mod.rs"]
mod corpus;

/// The pane shape every test starts from: unified, whitespace as written, 66 columns, 20 rows — the
/// size the golden files use, so a row count here means the same thing it means there.
fn request(scroll: usize) -> Request {
    Request {
        layout: Layout::Unified,
        ignore_ws: false,
        word_diff: false,
        width: 66,
        height: 20,
        scroll,
    }
}

/// A loaded view over generated bytes, in the shape a real session has: index built, file chosen.
fn loaded(text: &str, budget: Budget) -> DiffView {
    let mut view = DiffView::with_budget(budget);
    view.load(Box::new(BytesSource::new("episode", String::from(text))))
        .expect("the fixture loads");
    assert!(view.ensure_file().is_some(), "the fixture has a file");
    view
}

/// A view that serves hunks from the decode cache and decodes nothing on its own — the threaded
/// policy, driven by this thread instead of by workers. Every test that cares about the frames a
/// background decode makes uses this, because two real threads answer a request before the frame that
/// asked for it is even drawn, and the interesting frames are the ones in between.
fn cached(text: &str, budget: Budget) -> DiffView {
    let view = loaded(text, budget);
    view.serve_from_cache();
    view
}

/// The same with real workers, for the tests that want to prove the threads exist and report.
fn threaded(text: &str, budget: Budget) -> (DiffView, Arc<Bus>) {
    let view = loaded(text, budget);
    let bus = Bus::new();
    view.spawn_workers(Arc::clone(&bus));
    (view, bus)
}

/// The pane's text, for comparisons that are about content and not about styling.
fn text_of(doc: &fathom_tui::diff::Doc) -> Vec<String> {
    doc.lines
        .iter()
        .map(|line| line.text().to_owned())
        .collect()
}

// --- criterion 1: 5 000 files paint in under 300 ms --------------------------------------------------

#[test]
fn opening_five_thousand_files_paints_the_first_frame_under_300ms() {
    let text = corpus::generated(5000, 1, 6);
    let started = Instant::now();
    let view = loaded(&text, Budget::DEFAULT);
    let loaded_in = started.elapsed();

    // The frame: the tree pane's 24 rows and the hunks pane's 20, drawn the way the shell draws them.
    let started = Instant::now();
    let tree = view.tree_window(0, 22, 44);
    let file = view.file.expect("a file is selected");
    let doc = view.build(file, &request(0));
    let painted_in = started.elapsed();

    println!(
        "5 000 files, {} patch bytes: load {loaded_in:?}, first frame {painted_in:?}",
        text.len()
    );
    assert_eq!(tree.len(), 22, "the tree pane drew its window");
    assert_eq!(doc.pending, 0, "the inline path has nothing pending");

    let total = loaded_in + painted_in;
    assert!(
        total < std::time::Duration::from_millis(300),
        "opening a 5 000-file episode took {total:?} (load {loaded_in:?} + frame {painted_in:?}); \
         the criterion is 300 ms"
    );
}

#[test]
fn a_tree_frame_costs_its_height_and_not_its_index() {
    // The structural half of the same criterion, so the timing test above is a measurement and not a
    // race: doubling the index must not double the frame. Rows drawn is the honest unit — a pane that
    // quietly went back to building every row would show it here before it showed up on a laptop.
    let small = corpus::generated(400, 1, 6);
    let big = corpus::generated(4000, 1, 6);
    let small = loaded(&small, Budget::DEFAULT);
    let big = loaded(&big, Budget::DEFAULT);

    let started = Instant::now();
    for _ in 0..50 {
        std::hint::black_box(big.tree_window(0, 22, 44));
    }
    let big_frame = started.elapsed();
    let started = Instant::now();
    for _ in 0..50 {
        std::hint::black_box(small.tree_window(0, 22, 44));
    }
    let small_frame = started.elapsed();

    println!(
        "tree window: 400 files {small_frame:?}, 4 000 files {big_frame:?} ({} vs {} rows in the \
         index)",
        small.tree_len(),
        big.tree_len()
    );
    assert!(
        small.tree_len() >= 400,
        "the small index is the size it says"
    );
    assert!(
        big.tree_len() >= 4_000 && big.tree_len() < small.tree_len() * 11,
        "the two indexes are not ten times apart: {} vs {}",
        small.tree_len(),
        big.tree_len()
    );
    // Ten times the files, and the frame may cost at most four times as much — the slack is the
    // cached shape, which is the one O(files) pass a view is allowed to make.
    assert!(
        big_frame < small_frame.mul_f32(4.0) + std::time::Duration::from_millis(20),
        "a tree frame grew with the index: {small_frame:?} at 400 files against {big_frame:?} at \
         4 000"
    );
}

// --- criterion 2: the decode cache is bounded ---------------------------------------------------------

#[test]
fn the_decode_cache_never_holds_more_than_its_cap() {
    // The workload that would exceed it: one file, sixteen hunks of 40 lines, a cache room for about
    // two of them. An unbounded cache would hold all sixteen; this one holds the cap and says so.
    let text = corpus::generated(1, 60, 40);
    let budget = Budget {
        decode_bytes: 16 * 1024,
        ..Budget::DEFAULT
    };
    let view = cached(&text, budget);
    let file = view.file.expect("a file");
    let entry = view.file_at(file).expect("the file is indexed");
    assert!(
        entry.hunks.len() >= 60,
        "the fixture is the workload: {} hunks",
        entry.hunks.len()
    );
    let whole = entry
        .hunks
        .iter()
        .map(|hunk| hunk.byte_end - hunk.byte_start)
        .sum::<u64>();
    let cap = u64::try_from(budget.decode_bytes).unwrap_or(u64::MAX);
    assert!(
        cap * 2 < whole,
        "the test has to be able to overflow the cap: {whole} bytes of hunks against a {cap} B \
         cap, and a hunk has to fit in the cache on its own or the eviction test proves nothing"
    );

    let shape = Shape::of(Layout::Unified, false);
    view.materializer().request(
        view.origin().expect("an origin"),
        entry,
        shape,
        (0, entry.hunks.len()),
        0,
    );
    view.drain_decodes();
    // Read them back: a cache that is only ever written to is not being bounded, it is being filled.
    let _frame = view.build(file, &request(0));

    let stats = view.materializer().stats();
    println!(
        "cache: {} B of {} B cap, {} entries, {} evictions, {} hits / {} misses",
        stats.cache.bytes,
        stats.cache.max_bytes,
        stats.cache.entries,
        stats.cache.evictions,
        stats.cache.hits,
        stats.cache.misses
    );
    assert!(
        stats.cache.bytes <= stats.cache.max_bytes,
        "the decode cache holds {} B over a {} B cap",
        stats.cache.bytes,
        stats.cache.max_bytes
    );
    assert!(
        stats.cache.evictions > 0,
        "nothing was evicted, so the cap was never the thing that bounded it"
    );
    assert!(
        (stats.cache.hits + stats.cache.misses) > 0,
        "the cache was never read"
    );
}

#[test]
fn a_single_piece_bigger_than_the_whole_cache_is_refused_and_says_so() {
    // The case a byte-bounded cache has to answer honestly: one hunk larger than the cap. It is not
    // squeezed in, not silently dropped, and not forgotten about — the pane prints the sentence.
    let text = corpus::generated(1, 2, 300);
    let budget = Budget {
        decode_bytes: 512,
        ..Budget::DEFAULT
    };
    let view = loaded(&text, budget);
    let file = view.file.expect("a file");
    let entry = view.file_at(file).expect("indexed");
    let shape = Shape::of(Layout::Unified, false);
    view.materializer()
        .request(view.origin().expect("origin"), entry, shape, (0, 1), 0);
    view.drain_decodes();

    let stats = view.materializer().stats();
    assert_eq!(stats.cache.refused, 1, "one oversized piece, refused");
    assert_eq!(stats.cache.bytes, 0, "and nothing cached");
    let key = fathom_tui::diff::Key::new(
        view.origin().expect("origin"),
        &entry.path,
        shape,
        fathom_tui::diff::Plan::of(0, &entry.hunks[0]),
    );
    let why = view
        .materializer()
        .engine()
        .failure(&key)
        .expect("the refusal is stated");
    assert!(
        why.contains("512"),
        "the refusal has to name the cap it lost to: {why}"
    );
}

// --- criterion 3: rapid scrolling cannot queue unbounded work ---------------------------------------

#[test]
fn a_wide_window_never_queues_more_than_the_cap() {
    // The shape that can overflow a queue: a tall pane over a file with more hunks than the cap, asked
    // for again and again without anything running the answers. Nothing is superseded here — the
    // window never moves — so the only thing between this and an unbounded queue is the cap.
    let text = corpus::generated(1, 200, 20);
    let budget = Budget {
        max_in_flight: 16,
        prefetch_hunks: 4,
        ..Budget::DEFAULT
    };
    let view = loaded(&text, budget);
    let file = view.file.expect("a file");
    let entry = view.file_at(file).expect("indexed");
    let origin = view.origin().expect("origin").to_owned();
    let shape = Shape::of(Layout::Unified, false);
    let cap = budget.max_in_flight;

    let mut peak = 0_usize;
    for step in 0..1000_usize {
        let first = step;
        let last = first + 40;
        view.materializer()
            .request(&origin, entry, shape, (first, last), budget.prefetch_hunks);
        let stats = view.materializer().stats();
        let in_flight = stats.queued + stats.running;
        peak = peak.max(in_flight);
        assert!(
            in_flight <= cap,
            "after request {step} the engine is holding {in_flight} jobs against a cap of {cap}"
        );
    }
    let stats = view.materializer().stats();
    println!(
        "1 000 wide requests: peak {peak} in flight against a cap of {cap}, {} admitted, {} refused",
        stats.counts.admitted, stats.counts.dropped
    );
    assert_eq!(peak, cap, "the queue filled up to the cap, and no further");
    assert_eq!(
        stats.counts.peak_in_flight, cap,
        "and the queue counted its own peak"
    );
    assert!(
        stats.counts.dropped > 0,
        "nothing was ever refused, so the cap never bound"
    );
    assert!(
        stats.queued + stats.running <= cap,
        "and the queue is still no wider than the cap"
    );
}

#[test]
fn a_thousand_scrolls_supersede_the_windows_they_left() {
    // The other half of the same promise. A cap alone is not enough: a queue of 32 hunks nobody is
    // looking at is still 32 decodes of work the reviewer has already scrolled past, each one
    // arriving as a frame. Scrolling has to *take them out*.
    let text = corpus::generated(1, 200, 20);
    let budget = Budget {
        max_in_flight: 16,
        prefetch_hunks: 4,
        ..Budget::DEFAULT
    };
    let view = loaded(&text, budget);
    let file = view.file.expect("a file");
    let entry = view.file_at(file).expect("indexed");
    let origin = view.origin().expect("origin").to_owned();
    let shape = Shape::of(Layout::Unified, false);
    let cap = budget.max_in_flight;

    let mut peak = 0_usize;
    for step in 0..1000_usize {
        let first = step % entry.hunks.len().saturating_sub(4);
        let last = (first + 4).min(entry.hunks.len());
        view.materializer()
            .request(&origin, entry, shape, (first, last), budget.prefetch_hunks);
        let stats = view.materializer().stats();
        let in_flight = stats.queued + stats.running;
        peak = peak.max(in_flight);
        assert!(
            in_flight <= cap,
            "after scroll {step} the engine is holding {in_flight} jobs against a cap of {cap}"
        );
        assert_eq!(
            Priority::Visible as u8,
            0,
            "the visible tier is the one that gets run first"
        );
    }
    let stats = view.materializer().stats();
    println!(
        "1 000 scrolls: peak {peak} in flight against a cap of {cap}, {} superseded, {} interrupted",
        stats.counts.superseded, stats.counts.interrupted
    );
    assert!(
        stats.counts.superseded > 100,
        "the scrolls superseded almost nothing — the queue is capped, not cleaned: {}",
        stats.counts.superseded
    );
    assert!(
        peak <= cap / 2,
        "a cleaned queue should never get near the cap on its own: peak {peak} of {cap}"
    );
}

#[test]
fn scrolling_past_a_queued_hunk_cancels_it_instead_of_finishing_it() {
    // The other half of "no unbounded work": the work that is already running stops too, and its
    // result is dropped rather than cached, because nobody is looking at that window any more.
    let text = corpus::generated(1, 40, 20);
    let view = loaded(&text, Budget::DEFAULT);
    let file = view.file.expect("a file");
    let entry = view.file_at(file).expect("indexed");
    let origin = view.origin().expect("origin").to_owned();
    let shape = Shape::of(Layout::Unified, false);

    // Ask for the far end of the file, take one job (as a worker would), then scroll away.
    view.materializer()
        .request(&origin, entry, shape, (20, 24), 0);
    let running = view
        .materializer()
        .engine()
        .take()
        .expect("a job was queued");
    view.materializer()
        .request(&origin, entry, shape, (0, 4), 0);

    assert!(
        running.cancel.is_cancelled(),
        "the job that was still running for the old window was not told to stop"
    );
    let stats = view.materializer().stats();
    assert!(
        stats.counts.superseded + stats.counts.interrupted > 0,
        "the supersede was not counted: {stats:?}"
    );
}

// --- criterion 4: never stale, and correct as soon as it can be --------------------------------------

/// Which hunks a frame's rows actually came from. The fixture marks every line with its hunk number,
/// so this is a parse and not a guess.
///
/// The check the fourth criterion turns on: a frame may show a hunk that arrived early from a
/// prefetch, but it may never show a hunk that is not in its own window, and a hunk it has not got
/// must be a stated hole rather than somebody else's rows.
fn hunks_in(text: &str) -> Vec<usize> {
    let mut found: Vec<usize> = Vec::new();
    let mut tokens = text.split_whitespace();
    while let Some(token) = tokens.next() {
        if token != "-old" && token != "+new" {
            continue;
        }
        let Some(label) = tokens.next() else { continue };
        let mut parts = label.split('-');
        // "0-7-3" is file-hunk-line; the field with the hunk number is the second.
        let _file = parts.next();
        if let Some(hunk) = parts.next().and_then(|field| field.parse::<usize>().ok())
            && !found.contains(&hunk)
        {
            found.push(hunk);
        }
    }
    found.sort_unstable();
    found
}

#[test]
fn a_window_that_has_not_arrived_is_a_stated_hole_and_nobody_elses_content() {
    let text = corpus::generated(1, 30, 12);
    let view = cached(&text, Budget::DEFAULT);
    let inline = loaded(&text, Budget::DEFAULT);
    let file = view.file.expect("a file");

    // Jump to a window deep in the file with nothing decoded at all.
    let deep = request(240);
    let doc = view.build(file, &deep);
    let drawn = text_of(&doc).join("\n");
    assert!(doc.pending > 0, "the window should be missing hunks");
    assert!(
        drawn.contains("is being decoded"),
        "a missing hunk has to announce itself: {drawn}"
    );
    assert!(
        !drawn.contains("-old 0-0-0"),
        "the pane showed the top of the file while asked for a window deep in it"
    );
    assert!(
        hunks_in(&drawn).is_empty(),
        "nothing was decoded, and yet rows arrived: {:?}",
        hunks_in(&drawn)
    );

    // Answer the request, and the same frame becomes the inline frame row for row.
    view.drain_decodes();
    let filled = view.build(file, &deep);
    assert_eq!(filled.pending, 0, "the queue had answered by now");
    assert_eq!(
        text_of(&filled),
        text_of(&inline.build(file, &deep)),
        "a cached window and an inline window must be the same window"
    );
    assert_eq!(filled.shape, Shape::of(Layout::Unified, false));
}

#[test]
fn a_shape_change_is_a_cache_miss_and_never_the_old_shapes_rows() {
    // The failure mode "never stale" is really about: split rows drawn into a unified pane, or the
    // other way round, because the cache was keyed on the file and not on what was asked of it.
    let text = corpus::generated(1, 12, 12);
    let view = cached(&text, Budget::DEFAULT);
    let inline = loaded(&text, Budget::DEFAULT);
    let file = view.file.expect("a file");
    let unified = request(0);
    // Draw once to submit the request, answer it, then draw again: the frame that matters is the one
    // after the answers.
    let _asking = view.build(file, &unified);
    view.drain_decodes();
    let before = view.build(file, &unified);
    assert_eq!(before.pending, 0, "the unified window was served");

    let mut split = unified;
    split.layout = Layout::Split;
    split.width = 120;
    let after = view.build(file, &split);
    assert_eq!(before.shape, Shape::of(Layout::Unified, false));
    assert_eq!(after.shape, Shape::of(Layout::Split, false));
    assert_ne!(
        text_of(&before),
        text_of(&after),
        "the pane redrew nothing for a shape change, so it is still showing the old shape"
    );
    assert!(
        after.pending > 0,
        "a shape nobody has decoded for must be a hole, not the other shape's rows: {}",
        text_of(&after).join(" / ")
    );

    view.drain_decodes();
    let settled = view.build(file, &split);
    assert_eq!(settled.pending, 0);
    assert_eq!(
        text_of(&settled),
        text_of(&inline.build(file, &split)),
        "the split window that arrived is not the split window the inline path would draw"
    );
}

#[test]
fn rapid_next_next_next_never_shows_the_previous_window() {
    // The reviewer presses `]` three times fast. Nothing is decoded in advance except what the first
    // window's prefetch managed to finish, and each frame is checked twice over: that everything in it
    // belongs to that frame's own window, and that once its own hunks land it is the inline frame.
    let text = corpus::generated(1, 24, 12);
    let view = cached(&text, Budget::DEFAULT);
    let inline = loaded(&text, Budget::DEFAULT);
    let file = view.file.expect("a file");

    // Each hunk is 12 removed + 12 added + header = 25 rows, so a 20-row window steps by 25.
    let windows: Vec<Request> = (0..3_usize).map(|step| request(step * 25)).collect();
    let mut hole_in_each = Vec::new();
    for window in &windows {
        let doc = view.build(file, window);
        let drawn = text_of(&doc).join("\n");
        // Nothing outside this window's own hunks, before the answers or after them.
        let (first, last) = view.window(file, window);
        for hunk in hunks_in(&drawn) {
            assert!(
                (first..last).contains(&hunk),
                "a frame for hunks {first}..{last} is showing hunk {hunk}: {drawn}"
            );
        }
        hole_in_each.push(doc.pending);

        // Only this window gets served, which is the worst case for staleness: whatever an earlier
        // frame asked for that has not landed yet is stale by the time it does.
        view.drain_decodes();
        let settled = view.build(file, window);
        assert_eq!(settled.pending, 0, "this window's own queue was drained");
        assert_eq!(
            text_of(&settled),
            text_of(&inline.build(file, window)),
            "a frame is not the window it was asked for"
        );
    }
    // The last frame, in particular: three requests deep, it is the third window and not the first.
    assert!(
        hole_in_each.iter().any(|hole| *hole > 0),
        "no frame was ever missing a hunk, so this test proved nothing about holes: {hole_in_each:?}"
    );
}

// --- pre-warming the next and the previous episode ---------------------------------------------------

#[test]
fn a_warmed_episode_opens_without_reading_the_patch_again() {
    let next = corpus::generated(6, 3, 10);
    let current = corpus::generated(2, 2, 6);
    let mut view = cached(&current, Budget::DEFAULT);

    // Offer the neighbour, then wait (bounded) for the warm-up thread to publish its index.
    let origin = view
        .prewarm(
            "next",
            Box::new(BytesSource::new("episode-next", String::from(&next))),
        )
        .expect("the neighbour is warmable");
    let deadline = Instant::now() + std::time::Duration::from_secs(5);
    loop {
        view.drain_decodes();
        if view
            .warm_words(&origin)
            .is_some_and(|said| said.contains("warmed"))
        {
            break;
        }
        assert!(
            Instant::now() < deadline,
            "the warm-up never finished: {:?}",
            view.warm_words(&origin)
        );
        std::thread::sleep(std::time::Duration::from_millis(2));
    }
    println!("warm-up: {}", view.warm_words(&origin).expect("words"));

    // Opening it must reuse both halves of the work: the index it scanned and the hunks it decoded.
    view.load(Box::new(BytesSource::new(
        "episode-next",
        String::from(&next),
    )))
    .expect("the neighbour opens");
    view.ensure_file();
    let file = view.file.expect("a file");
    let misses = view.materializer().stats().cache.misses;
    let doc = view.build(file, &request(0));
    let stats = view.materializer().stats();
    println!(
        "first frame of a warmed episode: {} rows, {} pending, {} cache hits / {} misses",
        doc.doc_rows, doc.pending, stats.cache.hits, stats.cache.misses
    );
    assert_eq!(
        doc.pending, 0,
        "the warm-up did not decode the first window"
    );
    assert_eq!(
        stats.cache.misses, misses,
        "the first frame asked for hunks the warm-up had not decoded"
    );
    assert!(stats.cache.hits > 0, "nothing came from the warm-up");
}

#[test]
fn a_reloaded_patch_invalidates_every_hunk_decoded_from_the_old_bytes() {
    // A reload says "the bytes moved". An offset into the old bytes is the one thing a decode cache
    // must never be allowed to draw, so every entry for that origin goes with the old bytes.
    let first = corpus::generated(1, 4, 6);
    let second = corpus::generated(1, 4, 9);
    let mut view = cached(&first, Budget::DEFAULT);
    let file = view.file.expect("a file");
    let _asking = view.build(file, &request(0));
    view.drain_decodes();
    assert!(
        view.materializer().stats().cache.entries > 0,
        "the first patch was never decoded, so there is nothing to invalidate"
    );

    view.load(Box::new(BytesSource::new("episode", String::from(&second))))
        .expect("a second patch under a name that was already used");
    assert_eq!(
        view.materializer().stats().cache.entries,
        0,
        "a load under a used name kept the old bytes' hunks"
    );
    view.ensure_file();
    let file = view.file.expect("the second patch has a file");
    let _asking = view.build(file, &request(0));
    view.drain_decodes();
    assert_eq!(
        text_of(&view.build(file, &request(0))),
        text_of(&loaded(&second, Budget::DEFAULT).build(file, &request(0))),
        "the pane is still saying what the old bytes said"
    );
}

#[test]
fn real_workers_answer_a_window_and_say_so_on_the_bus() {
    // The one thing only threads can prove: that a miss is answered without the pane asking, and that
    // the answer arrives as a message rather than as a stall.
    let text = corpus::generated(1, 8, 12);
    let (view, bus) = threaded(&text, Budget::DEFAULT);
    let file = view.file.expect("a file");
    let doc = view.build(file, &request(0));
    let drawn = text_of(&doc).join("\n");

    let mut said = Vec::new();
    let deadline = Instant::now() + std::time::Duration::from_secs(5);
    while said.is_empty() {
        assert!(
            Instant::now() < deadline,
            "the workers never had anything to say (first frame: {drawn})"
        );
        if let fathom_tui::event::Received::Message(message) =
            bus.recv_timeout(std::time::Duration::from_millis(20))
        {
            said.push(format!("{message:?}"));
        }
    }
    println!("first frame pending {}, bus said {said:?}", doc.pending);
    assert!(
        said.iter()
            .any(|line| line.contains("Quiet") || line.contains("Progress")),
        "the workers reported something else entirely: {said:?}"
    );
}
